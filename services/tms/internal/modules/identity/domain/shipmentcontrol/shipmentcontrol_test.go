package shipmentcontrol_test

import (
	"testing"

	"github.com/emoss08/trenova/internal/modules/identity/domain/shipmentcontrol"
	"github.com/emoss08/trenova/pkg/errortypes"
	"github.com/emoss08/trenova/shared/pulid"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func flatDetention() *shipmentcontrol.ShipmentControl {
	threshold := int16(120)
	charge := pulid.MustNew("acc_")

	return &shipmentcontrol.ShipmentControl{
		MaxShipmentWeightLimit: 80000,
		TrackDetentionTime:     true,
		DetentionThreshold:     &threshold,
		DetentionChargeID:      &charge,
	}
}

func TestValidate_TracksDetentionWithoutAutomaticCharges(t *testing.T) {
	t.Parallel()

	control := flatDetention()
	control.AutoGenerateDetentionCharges = false

	multiErr := errortypes.NewMultiError()
	control.Validate(multiErr)

	assert.False(t, multiErr.HasErrors(), "tracking detention without automatic charges is valid: %v", multiErr)
}

func TestValidate_AutomaticChargesRequireTracking(t *testing.T) {
	t.Parallel()

	control := flatDetention()
	control.TrackDetentionTime = false
	control.AutoGenerateDetentionCharges = true

	multiErr := errortypes.NewMultiError()
	control.Validate(multiErr)

	require.Len(t, multiErr.Errors, 1)
	assert.Equal(t, "trackDetentionTime", multiErr.Errors[0].Path.String())
	assert.Equal(
		t,
		"Track detention time is required when auto generate detention charges is true",
		multiErr.Errors[0].Message,
	)
}
