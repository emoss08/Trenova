const (
	reserveSourceObject = "FactoringSubmissionItem"
	reserveEntryType    = "Standard"
)

type movementInput struct {
	scope     *ledgerScope
	item      *factoring.SubmissionItem
	movement  factoring.Movement
	event     tenant.JournalSourceEventType
	key       string
	date      int64
	dateField string
	memo      string
	reverses  pulid.ID
	remitLine pulid.ID
	actor     *permissionports.RequestActor
}

func (in *movementInput) tenantInfo() pagination.TenantInfo {
	return pagination.TenantInfo{
		OrgID: in.scope.before.OrganizationID,
		BuID:  in.scope.before.BusinessUnitID,
	}
}

func (in *movementInput) description() string {
	number, schedule := in.item.InvoiceNumber, in.scope.before.Number
	switch in.movement.Kind {
	case factoring.ReserveEntryFunding:
		return "Factor advance on invoice " + number + ", schedule " + schedule
	case factoring.ReserveEntryRelease:
		return "Factor reserve released on invoice " + number + ", schedule " + schedule
	case factoring.ReserveEntryChargeback:
		return "Factor chargeback of invoice " + number + ", schedule " + schedule
	case factoring.ReserveEntryChargebackReversal:
		return "Factor chargeback reversed on invoice " + number + ", schedule " + schedule
	default:
		return "Factoring of invoice " + number + ", schedule " + schedule
	}
}

func (s *LedgerService) writeRequest(in *movementInput) *journalposting.WriteRequest {
	description := in.description()
	lines := make([]journalposting.Line, 0, len(in.movement.Lines))
	for _, line := range in.movement.Lines {
		lines = append(lines, journalposting.Line{
			AccountID:   in.scope.accounts.For(line.Role),
			Debit:       line.Debit,
			Credit:      line.Credit,
			CustomerID:  in.item.CustomerID,
			Description: description,
		})
	}
	return &journalposting.WriteRequest{
		OrganizationID: in.scope.before.OrganizationID,
		BusinessUnitID: in.scope.before.BusinessUnitID,
		Control:        in.scope.control,
		ActorID:        in.actor.ExecutorUserID(),
		AccountingDate: in.date,
		Now:            s.now(),
		Subject:        "factoring entry",
		DateField:      in.dateField,
		Description:    description,
		Source: journalposting.Source{
			ObjectType:     reserveSourceObject,
			ObjectID:       in.item.ID,
			DocumentNumber: in.item.InvoiceNumber,
			Event:          in.event,
			IdempotencyKey: in.key,
		},
		EntryType:     reserveEntryType,
		Reference:     journalposting.Reference{Type: in.event.String(), ID: in.item.ID},
		AutoGenerated: true,
		Lines:         lines,
	}
}

func (s *LedgerService) planMovement(
	ctx context.Context,
	in *movementInput,
) (*factoringports.PlannedMovement, error) {
	planned := &factoringports.PlannedMovement{
		ItemID:         in.item.ID,
		InvoiceID:      in.item.InvoiceID,
		InvoiceNumber:  in.item.InvoiceNumber,
		CustomerID:     in.item.CustomerID,
		Movement:       in.movement,
		RequestedDate:  in.date,
		AccountingDate: in.date,
	}
	if in.movement.IsEmpty() {
		return planned, nil
	}
	plan, err := s.writer.Plan(ctx, s.writeRequest(in))
	if err != nil {
		return nil, err
	}
	planned.Lines = make([]factoringports.PlannedLine, 0, len(in.movement.Lines))
	for _, line := range in.movement.Lines {
		planned.Lines = append(planned.Lines, factoringports.PlannedLine{
			Role:      line.Role,
			AccountID: in.scope.accounts.For(line.Role),
			Debit:     line.Debit,
			Credit:    line.Credit,
		})
	}
	planned.AccountingDate = plan.AccountingDate
	if plan.Period != nil {
		planned.FiscalPeriodID = plan.Period.ID
		planned.FiscalPeriodName = plan.Period.Name
	}
	planned.EntryStatus = plan.Workflow.EntryStatus
	planned.RequiresApproval = !plan.Workflow.Posted()
	return planned, nil
}

func (s *LedgerService) postMovement(
	ctx context.Context,
	in *movementInput,
) (*factoring.ReserveEntry, error) {
	if in.movement.IsEmpty() {
		return nil, nil //nolint:nilnil // an empty movement books nothing and leaves no ledger row
	}
	result, err := s.writer.Write(ctx, s.writeRequest(in))
	if err != nil {
		return nil, err
	}
	entry := factoring.NewReserveEntry(in.item, in.scope.before, &in.movement, in.date)
	entry.ID = pulid.MustNew("facres_")
	entry.JournalEntryID = result.EntryID
	entry.JournalBatchID = result.BatchID
	entry.AccountingDate = result.AccountingDate
	entry.ReversesEntryID = in.reverses
	entry.RemittanceLineID = in.remitLine
	entry.Memo = stringutils.TruncateRunes(in.memo, factoring.MaxReserveMemoLength)
	entry.CreatedByID = in.actor.ExecutorUserID()
	created, err := s.entries.Create(ctx, entry)
	if err != nil {
		return nil, err
	}
	if err = s.applyInvoiceEffect(ctx, in, created); err != nil {
		return nil, err
	}
	return created, nil
}

func (s *LedgerService) applyInvoiceEffect(
	ctx context.Context,
	in *movementInput,
	entry *factoring.ReserveEntry,
) error {
	if in.movement.InvoiceEffect == factoring.InvoiceEffectNone {
		return nil
	}
	inv, err := s.invoices.LockForUpdate(ctx, invoiceports.GetInvoiceByIDRequest{
		ID:         in.item.InvoiceID,
		TenantInfo: in.tenantInfo(),
	})
	if err != nil {
		return err
	}
	amount := in.movement.InvoiceMinor
	if err = checkInvoiceEffect(inv, in.movement.InvoiceEffect, amount); err != nil {
		return err
	}
	signed := amount
	switch in.movement.InvoiceEffect {
	case factoring.InvoiceEffectSettle:
		inv.ApplyPaymentMinor(amount)
		signed = -amount
	case factoring.InvoiceEffectReopen:
		inv.RemovePaymentMinor(amount)
	case factoring.InvoiceEffectNone:
	}
	if _, err = s.invoices.Update(ctx, inv); err != nil {
		return err
	}
	if s.ledger == nil {
		return nil
	}
	return s.ledger.AppendEntries(ctx, []*customerledger.CustomerLedgerEntry{{
		ID:               pulid.MustNew("cledg_"),
		OrganizationID:   inv.OrganizationID,
		BusinessUnitID:   inv.BusinessUnitID,
		CustomerID:       inv.CustomerID,
		SourceObjectType: reserveSourceObject,
		SourceObjectID:   entry.ID.String(),
		SourceEventType:  in.event.String(),
		RelatedInvoiceID: inv.ID,
		DocumentNumber:   in.scope.before.Number,
		TransactionDate:  entry.AccountingDate,
		LineNumber:       1,
		AmountMinor:      signed,
		CreatedByID:      in.actor.ExecutorUserID(),
	}})
}

func checkInvoiceEffect(inv *invoice.Invoice, effect factoring.InvoiceEffect, amount int64) error {
	switch effect {
	case factoring.InvoiceEffectSettle:
		if inv.TotalAmountMinor-inv.AppliedAmountMinor < amount {
			return errortypes.NewBusinessError(
				"Invoice {0} no longer has the open balance the factor bought; record the payment it received first",
				inv.Number,
			)
		}
	case factoring.InvoiceEffectReopen:
		if inv.AppliedAmountMinor < amount {
			return errortypes.NewBusinessError(
				"Invoice {0} has had payments taken off since it was factored; reload it and try again",
				inv.Number,
			)
		}
	case factoring.InvoiceEffectNone:
	}
	return nil
}

func (s *LedgerService) checkInvoices(
	ctx context.Context,
	tenantInfo pagination.TenantInfo,
	inputs []*movementInput,
) error {
	ids := make([]pulid.ID, 0, len(inputs))
	for _, in := range inputs {
		if in.movement.InvoiceEffect != factoring.InvoiceEffectNone {
			ids = append(ids, in.item.InvoiceID)
		}
	}
	if len(ids) == 0 {
		return nil
	}
	found, err := s.invoices.GetByIDs(ctx, invoiceports.GetInvoicesByIDsRequest{
		TenantInfo: tenantInfo,
		InvoiceIDs: ids,
	})
	if err != nil {
		return err
	}
	byID := make(map[pulid.ID]*invoice.Invoice, len(found))
	for _, inv := range found {
		if inv != nil {
			byID[inv.ID] = inv
		}
	}
	for _, in := range inputs {
		if in.movement.InvoiceEffect == factoring.InvoiceEffectNone {
			continue
		}
		inv, ok := byID[in.item.InvoiceID]
		if !ok {
			return errortypes.NewNotFoundError("Invoice {0} was not found", in.item.InvoiceNumber)
		}
		if err = checkInvoiceEffect(
			inv,
			in.movement.InvoiceEffect,
			in.movement.InvoiceMinor,
		); err != nil {
			return err
		}
	}
	return nil
}
