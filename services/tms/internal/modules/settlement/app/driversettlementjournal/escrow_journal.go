func escrowRefundBooking(
	tx *payescrow.EscrowTransaction,
	control *accountingcontrol.AccountingControl,
) (*escrowBooking, error) {
	multiErr := errortypes.NewMultiError()
	if control.DefaultCashAccountID.IsNil() {
		multiErr.Add(
			"accountingControl",
			errortypes.ErrRequired,
			"A default cash account must be configured to post escrow refunds",
		)
	}
	if control.DefaultEscrowLiabilityAccountID.IsNil() {
		multiErr.Add(
			"accountingControl",
			errortypes.ErrRequired,
			"An escrow liability account must be configured to post escrow refunds",
		)
	}
	if multiErr.HasErrors() {
		return nil, multiErr
	}
	return &escrowBooking{
		event:          accountingcontrol.JournalSourceEventEscrowRefunded,
		keyPrefix:      "escrow-refunded:",
		subject:        "escrow refund",
		defaultSummary: "Escrow refund",
		lines: escrowLiabilityLines(
			control.DefaultEscrowLiabilityAccountID,
			control.DefaultCashAccountID,
			tx.AmountMinor,
		),
	}, nil
}

func escrowLiabilityLines(liabilityID, contraID pulid.ID, amount int64) []journalposting.Line {
	if amount > 0 {
		return []journalposting.Line{
			{AccountID: contraID, Debit: amount},
			{AccountID: liabilityID, Credit: amount},
		}
	}
	return []journalposting.Line{
		{AccountID: liabilityID, Debit: -amount},
		{AccountID: contraID, Credit: -amount},
	}
}

func (s *Writer) PostEscrowTransaction(
	ctx context.Context,
	account *payescrow.EscrowAccount,
	transaction *payescrow.EscrowTransaction,
) (*pulid.ID, error) {
	if transaction.AmountMinor == 0 || hasID(transaction.SettlementID) {
		return nil, nil //nolint:nilnil // settlement journals book movements that carry a settlement
	}
	control, err := s.accountingRepo.GetByOrgID(ctx, account.OrganizationID)
	if err != nil {
		return nil, err
	}
	request, err := EscrowJournal(&EscrowJournalRequest{
		Account:     account,
		Transaction: transaction,
		Control:     control,
		Now:         timeutils.NowUnix(),
	})
	if err != nil || request == nil {
		return nil, err
	}
	result, err := s.journalWriter().Write(ctx, request)
	if err != nil {
		return nil, err
	}
	return &result.BatchID, nil
}
