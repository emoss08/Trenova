const escrowTransactionSourceObject = "EscrowTransaction"

type EscrowJournalRequest struct {
	Account     *payescrow.EscrowAccount
	Transaction *payescrow.EscrowTransaction
	Control     *accountingcontrol.AccountingControl
	Now         int64
}

type escrowBooking struct {
	event          accountingcontrol.JournalSourceEventType
	keyPrefix      string
	subject        string
	defaultSummary string
	lines          []journalposting.Line
}

func EscrowJournal(req *EscrowJournalRequest) (*journalposting.WriteRequest, error) {
	tx := req.Transaction
	if tx.AmountMinor == 0 || hasID(tx.SettlementID) {
		return nil, nil //nolint:nilnil // settlement journals book movements that carry a settlement
	}

	booking, err := escrowBookingFor(tx, req.Control)
	if err != nil {
		return nil, err
	}

	description := booking.defaultSummary
	if tx.Description != "" {
		description = tx.Description
	}

	return &journalposting.WriteRequest{
		OrganizationID: req.Account.OrganizationID,
		BusinessUnitID: req.Account.BusinessUnitID,
		Control:        req.Control,
		ActorID:        tx.CreatedByID,
		AccountingDate: tx.OccurredDate,
		Now:            req.Now,
		Subject:        booking.subject,
		DateField:      "occurredDate",
		Description:    description,
		Source: journalposting.Source{
			ObjectType:     escrowTransactionSourceObject,
			ObjectID:       tx.ID,
			Event:          booking.event,
			IdempotencyKey: booking.keyPrefix + tx.ID.String(),
		},
		Reference: journalposting.Reference{
			Type: booking.event.String(),
			ID:   req.Account.ID,
		},
		AutoGenerated: true,
		Lines:         booking.lines,
	}, nil
}

func escrowBookingFor(
	tx *payescrow.EscrowTransaction,
	control *accountingcontrol.AccountingControl,
) (*escrowBooking, error) {
	switch tx.Type {
	case payescrow.EscrowTransactionTypeInterestAccrual:
		return escrowInterestBooking(tx, control)
	case payescrow.EscrowTransactionTypeAdjustment:
		return escrowAdjustmentBooking(tx, control)
	case payescrow.EscrowTransactionTypeRefund:
		return escrowRefundBooking(tx, control)
	case payescrow.EscrowTransactionTypeContribution,
		payescrow.EscrowTransactionTypeApplication:
		return nil, errortypes.NewValidationError(
			"type",
			errortypes.ErrInvalidOperation,
			"Escrow contributions and applications are booked by the settlement that carries them",
		)
	default:
		return nil, errortypes.NewValidationError(
			"type",
			errortypes.ErrInvalid,
			"Escrow transaction type is invalid",
		)
	}
}

func escrowInterestBooking(
	tx *payescrow.EscrowTransaction,
	control *accountingcontrol.AccountingControl,
) (*escrowBooking, error) {
	multiErr := errortypes.NewMultiError()
	if control.DefaultEscrowInterestExpenseAccountID.IsNil() {
		multiErr.Add(
			"accountingControl",
			errortypes.ErrRequired,
			"An escrow interest expense account must be configured to post escrow interest",
		)
	}
	if control.DefaultEscrowLiabilityAccountID.IsNil() {
		multiErr.Add(
			"accountingControl",
			errortypes.ErrRequired,
			"An escrow liability account must be configured to post escrow interest",
		)
	}
	if multiErr.HasErrors() {
		return nil, multiErr
	}
	return &escrowBooking{
		event:          accountingcontrol.JournalSourceEventEscrowInterestAccrued,
		keyPrefix:      "escrow-interest-accrued:",
		subject:        "escrow interest",
		defaultSummary: "Escrow interest accrual",
		lines: escrowLiabilityLines(
			control.DefaultEscrowLiabilityAccountID,
			control.DefaultEscrowInterestExpenseAccountID,
			tx.AmountMinor,
		),
	}, nil
}

