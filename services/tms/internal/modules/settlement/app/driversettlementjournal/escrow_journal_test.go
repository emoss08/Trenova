const escrowAccruedAt = int64(1_790_000_000)

func escrowAccrual(amount int64) (*payescrow.EscrowAccount, *payescrow.EscrowTransaction) {
	account := &payescrow.EscrowAccount{
		ID:             pulid.MustNew("escr_"),
		OrganizationID: pulid.MustNew("org_"),
		BusinessUnitID: pulid.MustNew("bu_"),
		Status:         payescrow.EscrowAccountStatusActive,
	}
	return account, &payescrow.EscrowTransaction{
		ID:              pulid.MustNew("esctx_"),
		OrganizationID:  account.OrganizationID,
		BusinessUnitID:  account.BusinessUnitID,
		EscrowAccountID: account.ID,
		Type:            payescrow.EscrowTransactionTypeInterestAccrual,
		AmountMinor:     amount,
		OccurredDate:    escrowAccruedAt,
		Description:     "Quarterly escrow interest accrual per 49 CFR 376.12(k)",
	}
}

func escrowControl() *accountingcontrol.AccountingControl {
	return &accountingcontrol.AccountingControl{
		JournalPostingMode:                    accountingcontrol.JournalPostingModeAutomatic,
		DefaultEscrowInterestExpenseAccountID: pulid.MustNew("gla_"),
		DefaultEscrowLiabilityAccountID:       pulid.MustNew("gla_"),
	}
}

func TestEscrowInterestJournalDebitsExpenseAndCreditsTheLiability(t *testing.T) {
	t.Parallel()

	account, accrual := escrowAccrual(4_125)
	control := escrowControl()

	request, err := EscrowJournal(&EscrowJournalRequest{
		Account:     account,
		Transaction: accrual,
		Control:     control,
		Now:         escrowAccruedAt + 5,
	})
	require.NoError(t, err)
	require.NotNil(t, request)

	assert.Equal(t, []journalposting.Line{
		{AccountID: control.DefaultEscrowInterestExpenseAccountID, Debit: 4_125},
		{AccountID: control.DefaultEscrowLiabilityAccountID, Credit: 4_125},
	}, request.Lines)
	assert.Equal(t, journalposting.Source{
		ObjectType:     "EscrowTransaction",
		ObjectID:       accrual.ID,
		Event:          accountingcontrol.JournalSourceEventEscrowInterestAccrued,
		IdempotencyKey: "escrow-interest-accrued:" + accrual.ID.String(),
	}, request.Source)
	assert.Equal(t, escrowAccruedAt, request.AccountingDate)
	assert.Equal(t, escrowAccruedAt+5, request.Now)
	assert.Equal(t, account.OrganizationID, request.OrganizationID)
	assert.Equal(t, account.BusinessUnitID, request.BusinessUnitID)
	assert.True(t, request.AutoGenerated)
	assert.Equal(t, account.ID, request.Reference.ID)
	assert.Equal(t, "Quarterly escrow interest accrual per 49 CFR 376.12(k)", request.Description)
}

func TestEscrowInterestJournalRefusesMissingAccounts(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		mutate   func(*accountingcontrol.AccountingControl)
		messages []string
	}{
		{
			name: "expense account unset",
			mutate: func(c *accountingcontrol.AccountingControl) {
				c.DefaultEscrowInterestExpenseAccountID = pulid.Nil
			},
			messages: []string{
				"An escrow interest expense account must be configured to post escrow interest",
			},
		},
		{
			name: "liability account unset",
			mutate: func(c *accountingcontrol.AccountingControl) {
				c.DefaultEscrowLiabilityAccountID = pulid.Nil
			},
			messages: []string{
				"An escrow liability account must be configured to post escrow interest",
			},
		},
		{
			name: "both unset",
			mutate: func(c *accountingcontrol.AccountingControl) {
				c.DefaultEscrowInterestExpenseAccountID = pulid.Nil
				c.DefaultEscrowLiabilityAccountID = pulid.Nil
			},
			messages: []string{
				"An escrow interest expense account must be configured to post escrow interest",
				"An escrow liability account must be configured to post escrow interest",
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			account, accrual := escrowAccrual(4_125)
			control := escrowControl()
			tt.mutate(control)

			request, err := EscrowJournal(&EscrowJournalRequest{
				Account:     account,
				Transaction: accrual,
				Control:     control,
				Now:         escrowAccruedAt,
			})
			require.Nil(t, request)

			var multiErr *errortypes.MultiError
			require.ErrorAs(t, err, &multiErr)
			require.Len(t, multiErr.Errors, len(tt.messages))
			for idx, message := range tt.messages {
				assert.Equal(t, "accountingControl", multiErr.Errors[idx].Field())
				assert.Equal(t, errortypes.ErrRequired, multiErr.Errors[idx].Code)
				assert.Equal(t, message, multiErr.Errors[idx].Message)
			}
		})
	}
}

