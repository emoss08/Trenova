func TestEscrowJournalBooksAdjustmentsAgainstTheEscrowAdjustmentAccount(t *testing.T) {
	t.Parallel()

	control := escrowMovementControl()
	actorID := pulid.MustNew("usr_")
	tests := []struct {
		name   string
		amount int64
		lines  []journalposting.Line
	}{
		{
			name:   "increase",
			amount: 2_500,
			lines: []journalposting.Line{
				{AccountID: control.DefaultEscrowAdjustmentAccountID, Debit: 2_500},
				{AccountID: control.DefaultEscrowLiabilityAccountID, Credit: 2_500},
			},
		},
		{
			name:   "decrease",
			amount: -2_000,
			lines: []journalposting.Line{
				{AccountID: control.DefaultEscrowLiabilityAccountID, Debit: 2_000},
				{AccountID: control.DefaultEscrowAdjustmentAccountID, Credit: 2_000},
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			account, adjustment := escrowAccrual(tt.amount)
			adjustment.Type = payescrow.EscrowTransactionTypeAdjustment
			adjustment.Description = "damage claim applied"
			adjustment.CreatedByID = actorID

			request, err := EscrowJournal(&EscrowJournalRequest{
				Account:     account,
				Transaction: adjustment,
				Control:     control,
				Now:         escrowAccruedAt + 5,
			})
			require.NoError(t, err)
			require.NotNil(t, request)

			assert.Equal(t, tt.lines, request.Lines)
			for _, line := range request.Lines {
				assert.NotEqual(t, control.DefaultPurchasedTransportationAccountID, line.AccountID)
			}
			assert.Equal(t, journalposting.Source{
				ObjectType:     "EscrowTransaction",
				ObjectID:       adjustment.ID,
				Event:          accountingcontrol.JournalSourceEventEscrowAdjusted,
				IdempotencyKey: "escrow-adjusted:" + adjustment.ID.String(),
			}, request.Source)
			assert.Equal(t, journalposting.Reference{
				Type: "EscrowAdjusted",
				ID:   account.ID,
			}, request.Reference)
			assert.Equal(t, escrowAccruedAt, request.AccountingDate)
			assert.Equal(t, actorID, request.ActorID)
			assert.Equal(t, "escrow adjustment", request.Subject)
			assert.Equal(t, "damage claim applied", request.Description)
			assert.True(t, request.AutoGenerated)
		})
	}
}

