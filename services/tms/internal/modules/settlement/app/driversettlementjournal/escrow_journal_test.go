func TestPostEscrowInterestWritesOnTheAccrualDateWithItsIdempotencyKey(t *testing.T) {
	t.Parallel()

	account, accrual := escrowAccrual(4_125)
	control := escrowControl()
	control.OrganizationID = account.OrganizationID

	accounting := tenantportsmock.NewMockAccountingControlRepository(t)
	accounting.EXPECT().
		GetByOrgID(mock.Anything, account.OrganizationID).
		Return(control, nil).
		Once()

	periods := fiscalperiodportsmock.NewMockFiscalPeriodRepository(t)
	periods.EXPECT().
		GetPeriodByDate(mock.Anything, fiscalperiodports.GetPeriodByDateRequest{
			OrgID: account.OrganizationID,
			BuID:  account.BusinessUnitID,
			Date:  escrowAccruedAt,
		}).
		Return(&fiscalperiod.FiscalPeriod{
			ID:           pulid.MustNew("fp_"),
			FiscalYearID: pulid.MustNew("fy_"),
			Status:       fiscalperiod.StatusOpen,
		}, nil).
		Once()

	var written journalentryports.CreateJournalPostingParams
	journals := journalentryportsmock.NewMockJournalPostingRepository(t)
	journals.EXPECT().
		CreatePosting(mock.Anything, mock.Anything).
		RunAndReturn(func(_ context.Context, params journalentryports.CreateJournalPostingParams) error {
			written = params
			return nil
		}).
		Once()

	writer := &Writer{
		accountingRepo:   accounting,
		fiscalPeriodRepo: periods,
		journalRepo:      journals,
		generator:        journalNumbers{},
	}
	batchID, err := writer.PostEscrowTransaction(t.Context(), account, accrual)
	require.NoError(t, err)
	require.NotNil(t, batchID)

	assert.Equal(t, *batchID, written.BatchID)
	assert.Equal(t, escrowAccruedAt, written.AccountingDate)
	assert.Equal(t, "EscrowInterestAccrued", written.SourceEventType)
	assert.Equal(t, "EscrowTransaction", written.SourceObjectType)
	assert.Equal(t, accrual.ID.String(), written.SourceObjectID)
	assert.Equal(t, "escrow-interest-accrued:"+accrual.ID.String(), written.SourceIdempotencyKey)
	assert.True(t, written.IsPosted)
	assert.True(t, written.IsAutoGenerated)
	assert.EqualValues(t, 4_125, written.TotalDebit)
	assert.EqualValues(t, 4_125, written.TotalCredit)
	require.Len(t, written.Lines, 2)
	assert.Equal(t, control.DefaultEscrowInterestExpenseAccountID, written.Lines[0].GLAccountID)
	assert.EqualValues(t, 4_125, written.Lines[0].DebitAmount)
	assert.Equal(t, control.DefaultEscrowLiabilityAccountID, written.Lines[1].GLAccountID)
	assert.EqualValues(t, 4_125, written.Lines[1].CreditAmount)
}

