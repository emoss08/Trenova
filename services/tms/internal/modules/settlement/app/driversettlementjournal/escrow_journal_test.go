func TestEscrowJournalRefusesContributionsAndApplicationsOutsideASettlement(t *testing.T) {
	t.Parallel()

	for _, tt := range []struct {
		txType payescrow.EscrowTransactionType
		amount int64
	}{
		{payescrow.EscrowTransactionTypeContribution, 500},
		{payescrow.EscrowTransactionTypeApplication, -500},
	} {
		account, movement := escrowAccrual(tt.amount)
		movement.Type = tt.txType
		request, err := EscrowJournal(&EscrowJournalRequest{
			Account:     account,
			Transaction: movement,
			Control:     escrowMovementControl(),
		})
		require.Nil(t, request)
		var validationErr *errortypes.Error
		require.ErrorAs(t, err, &validationErr)
		assert.Equal(t, "type", validationErr.Field())
		assert.Equal(t, errortypes.ErrInvalidOperation, validationErr.Code)
		assert.Equal(
			t,
			"Escrow contributions and applications are booked by the settlement that carries them",
			validationErr.Message,
		)
	}
}

