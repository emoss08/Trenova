func TestAdoptAndRecalculateContractRate_StillRatesWithoutRating(t *testing.T) {
	t.Parallel()

	entity := validShipment()
	linehaul := decimal.NewFromInt(1200)
	rated := &ratequoteports.RatedShipment{
		Amount:   linehaul,
		Total:    linehaul,
		Currency: "USD",
		Outcome:  ratequote.OutcomeRated,
		Bill:     shipmentcommercialtest.FreightBill(linehaul),
	}

	calculator := newCalculator(t, Params{
		Logger:     zap.NewNop(),
		RateEngine: ratequoteportsmock.NewMockRateEngine(t),
		Features:   plantest.BaseOnly(),
	})
	calculator.now = func() int64 { return shipmentcommercialtest.RatedAt }

	err := calculator.AdoptAndRecalculateContractRate(
		t.Context(),
		entity,
		rated,
		&shipmentcontrol.ShipmentControl{},
		pulid.MustNew("usr_"),
	)

	require.NoError(t, err)
	require.True(t, entity.FreightChargeAmount.Valid)
	assert.True(t, linehaul.Equal(entity.FreightChargeAmount.Decimal), "the contract still prices the freight")
	assert.True(t, linehaul.Equal(entity.TotalChargeAmount.Decimal))
}

func TestRecalculate_WithEveryFeatureOnRatesTheFormulaAndBillsDetentionAsBefore(t *testing.T) {
	t.Parallel()

	entity := validShipment()
	arrival := int64(100)
	entity.Moves[0].Stops[0].ActualArrival = &arrival
	control := detentionControl()

	calculator := newCalculator(t, Params{
		Logger:          zap.NewNop(),
		RateEngine:      shipmentcommercialtest.StubRateEngine(t, 100),
		AccessorialRepo: detentionAccessorial(t, entity, control),
		Features:        plantest.AllFeatures(),
	})
	calculator.now = func() int64 { return 7300 }

	err := calculator.Recalculate(t.Context(), entity, control, pulid.MustNew("usr_"))

	require.NoError(t, err)
	require.Len(t, entity.AdditionalCharges, 1)
	assert.True(t, entity.AdditionalCharges[0].IsDetention)
	assert.True(t, decimal.NewFromInt(100).Equal(entity.FreightChargeAmount.Decimal))
}
