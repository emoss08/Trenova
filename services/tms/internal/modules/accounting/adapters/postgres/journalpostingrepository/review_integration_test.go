func TestReviewApprovesAndPostsAPendingEntryIntoTheLedger(t *testing.T) {
	db := accountingtest.NewDevelopmentDatabase(t)
	ctx := db.A.Ctx
	kdb := db.Admin
	conn := db.Conn
	postings := New(Params{DB: conn, Logger: zap.NewNop()})
	review := NewReview(Params{DB: conn, Logger: zap.NewNop()})
	orgID, buID, userID, fiscalYearID, periodID, accountIDs := setupPostingFixture(t, db)
	tenantInfo := pagination.TenantInfo{OrgID: orgID, BuID: buID}
	accountingDate := time.Date(2027, time.January, 15, 0, 0, 0, 0, time.UTC).Unix()

	before, err := glaccountdb.GLAccounts.Get(ctx, kdb, accountIDs[0])
	require.NoError(t, err)

	batchID, entryID, sourceID := pulid.MustNew("jb_"), pulid.MustNew("je_"), pulid.MustNew("jsrc_")
	require.NoError(t, postings.CreatePosting(ctx, journalentryports.CreateJournalPostingParams{
		BatchID:              batchID,
		OrganizationID:       orgID,
		BusinessUnitID:       buID,
		BatchNumber:          "JB-R1",
		BatchType:            "System",
		BatchStatus:          "Pending",
		BatchDescription:     "Invoice posted for INV-1",
		FiscalYearID:         fiscalYearID,
		FiscalPeriodID:       periodID,
		AccountingDate:       accountingDate,
		CreatedByID:          userID,
		UpdatedByID:          userID,
		EntryID:              entryID,
		EntryNumber:          "JE-R1",
		EntryType:            "Standard",
		EntryStatus:          "Pending",
		ReferenceNumber:      "INV-1",
		ReferenceType:        "InvoicePosted",
		ReferenceID:          pulid.MustNew("inv_").String(),
		EntryDescription:     "Invoice posted for INV-1",
		TotalDebit:           2500,
		TotalCredit:          2500,
		IsAutoGenerated:      true,
		RequiresApproval:     true,
		SourceID:             sourceID,
		SourceObjectType:     "Invoice",
		SourceObjectID:       pulid.MustNew("inv_").String(),
		SourceEventType:      "InvoicePosted",
		SourceStatus:         "Pending",
		SourceDocumentNumber: "INV-1",
		SourceIdempotencyKey: "invoice-posted:review-1",
		Lines: []journalentryports.JournalPostingLine{
			{ID: pulid.MustNew("jel_"), GLAccountID: accountIDs[0], LineNumber: 1, DebitAmount: 2500, NetAmount: 2500},
			{ID: pulid.MustNew("jel_"), GLAccountID: accountIDs[1], LineNumber: 2, CreditAmount: 2500, NetAmount: -2500},
		},
	}))

	summary, err := review.Summarize(ctx, tenantInfo)
	require.NoError(t, err)
	assert.GreaterOrEqual(t, summary.AwaitingApproval, 1)
	require.NotNil(t, summary.OldestAccountingDate)
	assert.True(t, queueHolds(t, ctx, review, tenantInfo, entryID), "the pending entry waits for review")

	locked, err := review.LockEntry(ctx, journalentryports.LockJournalEntryRequest{TenantInfo: tenantInfo, EntryID: entryID})
	require.NoError(t, err)
	require.Len(t, locked.Lines, 2)
	assert.Equal(t, int16(1), locked.Lines[0].LineNumber)

	err = review.PostEntry(ctx, &journalentryports.PostJournalEntryParams{
		TenantInfo: tenantInfo, EntryID: entryID, BatchID: batchID, Version: locked.Version,
		FiscalYearID: fiscalYearID, FiscalPeriodID: periodID, AccountingDate: accountingDate,
		PostedByID: userID, PostedAt: accountingDate,
	})
	require.Error(t, err)
	assert.True(t, errortypes.IsConflictError(err), "a pending entry must not post")

	require.NoError(t, review.ApproveEntry(ctx, &journalentryports.ApproveJournalEntryParams{
		TenantInfo: tenantInfo, EntryID: entryID, BatchID: batchID, Version: locked.Version,
		ApprovedByID: userID, ApprovedAt: accountingDate,
	}))
	err = review.ApproveEntry(ctx, &journalentryports.ApproveJournalEntryParams{
		TenantInfo: tenantInfo, EntryID: entryID, BatchID: batchID, Version: locked.Version,
		ApprovedByID: userID, ApprovedAt: accountingDate,
	})
	require.Error(t, err)
	assert.True(t, errortypes.IsConflictError(err), "a stale version must not approve twice")

	approved, err := review.LockEntry(ctx, journalentryports.LockJournalEntryRequest{TenantInfo: tenantInfo, EntryID: entryID})
	require.NoError(t, err)
	assert.Equal(t, "Approved", string(approved.Status))
	assert.True(t, approved.IsApproved)
	assert.Equal(t, locked.Version+1, approved.Version)

	postedAt := accountingDate + 60
	require.NoError(t, review.PostEntry(ctx, &journalentryports.PostJournalEntryParams{
		TenantInfo: tenantInfo, EntryID: entryID, BatchID: batchID, Version: approved.Version,
		FiscalYearID: fiscalYearID, FiscalPeriodID: periodID, AccountingDate: accountingDate,
		PostedByID: userID, PostedAt: postedAt,
		Lines: []journalentryports.JournalPostingLine{
			{GLAccountID: accountIDs[0], DebitAmount: 2500, NetAmount: 2500},
			{GLAccountID: accountIDs[1], CreditAmount: 2500, NetAmount: -2500},
		},
	}))

	entry, err := journalentrydb.JournalEntries.Get(ctx, kdb, entryID)
	require.NoError(t, err)
	assert.Equal(t, journalentry.StatusPosted, entry.Status)
	assert.True(t, entry.IsPosted)
	require.NotNil(t, entry.PostedAt)
	assert.Equal(t, postedAt, *entry.PostedAt)

	batch, err := journalentrydb.JournalBatches.Get(ctx, kdb, batchID)
	require.NoError(t, err)
	assert.Equal(t, "Posted", batch.Status)
	require.NotNil(t, batch.PostedAt)

	source, err := journalsourcedb.Sources.Get(ctx, kdb, sourceID)
	require.NoError(t, err)
	assert.Equal(t, "Posted", source.Status)

	gb := glbalancedb.GLAccountPeriodBalances
	balance, err := gb.Where(
		gb.GLAccountID.Eq(accountIDs[0]),
		gb.FiscalPeriodID.Eq(periodID),
	).One(ctx, kdb)
	require.NoError(t, err)
	assert.Equal(t, int64(2500), balance.PeriodDebitMinor)
	assert.Equal(t, int64(2500), balance.NetChangeMinor)

	after, err := glaccountdb.GLAccounts.Get(ctx, kdb, accountIDs[0])
	require.NoError(t, err)
	assert.Equal(t, before.CurrentBalance+2500, after.CurrentBalance)
	assert.Equal(t, before.Version, after.Version)

	assert.False(t, queueHolds(t, ctx, review, tenantInfo, entryID), "a posted entry leaves the queue")

	err = review.PostEntry(ctx, &journalentryports.PostJournalEntryParams{
		TenantInfo: tenantInfo, EntryID: entryID, BatchID: batchID, Version: approved.Version + 1,
		FiscalYearID: fiscalYearID, FiscalPeriodID: periodID, AccountingDate: accountingDate,
		PostedByID: userID, PostedAt: postedAt,
	})
	require.Error(t, err)
	assert.True(t, errortypes.IsConflictError(err), "a posted entry must not post twice")

	stranger := pagination.TenantInfo{OrgID: pulid.MustNew("org_"), BuID: buID}
	_, err = review.LockEntry(dbscope.WithTenant(t.Context(), stranger.DBTenant()), journalentryports.LockJournalEntryRequest{
		TenantInfo: stranger,
		EntryID:    entryID,
	})
	require.Error(t, err)
	assert.True(t, errortypes.IsNotFoundError(err), "another tenant must not see the entry")
}

func queueHolds(
	t *testing.T,
	ctx context.Context,
	review journalentryports.JournalReviewRepository,
	tenantInfo pagination.TenantInfo,
	entryID pulid.ID,
) bool {
	t.Helper()
	result, err := review.ListConnection(ctx, &journalentryports.ListJournalReviewQuery{
		Filter: &pagination.QueryOptions{TenantInfo: tenantInfo},
		Cursor: pagination.CursorInfo{Limit: 100},
	})
	require.NoError(t, err)
	for _, item := range result.Items {
		if item.ID == entryID {
			return true
		}
	}
	return false
}
