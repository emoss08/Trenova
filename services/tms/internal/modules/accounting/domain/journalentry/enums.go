package journalentry

type EntryType string

const (
	EntryTypeStandard         = EntryType("Standard")
	EntryTypeAdjusting        = EntryType("Adjusting")
	EntryTypeClosing          = EntryType("Closing")
	EntryTypeReversal         = EntryType("Reversal")
	EntryTypeReclassification = EntryType("Reclassification")
	EntryTypeAutoGenerated    = EntryType("AutoGenerated")
	EntryTypeReconciliation   = EntryType("Reconciliation")
	EntryTypeOpening          = EntryType("Opening")
)

func (t EntryType) String() string { return string(t) }

func (t EntryType) IsValid() bool {
	switch t {
	case EntryTypeStandard,
		EntryTypeAdjusting,
		EntryTypeClosing,
		EntryTypeReversal,
		EntryTypeReclassification,
		EntryTypeAutoGenerated,
		EntryTypeReconciliation,
		EntryTypeOpening:
		return true
	default:
		return false
	}
}

type Status string

const (
	StatusDraft    = Status("Draft")
	StatusPending  = Status("Pending")
	StatusApproved = Status("Approved")
	StatusPosted   = Status("Posted")
	StatusReversed = Status("Reversed")
	StatusRejected = Status("Rejected")
	StatusVoid     = Status("Void")
)

func (s Status) String() string { return string(s) }

func (s Status) IsValid() bool {
	switch s {
	case StatusDraft,
		StatusPending,
		StatusApproved,
		StatusPosted,
		StatusReversed,
		StatusRejected,
		StatusVoid:
		return true
	default:
		return false
	}
}
