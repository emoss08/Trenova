func (e *JournalEntry) Validate(multiErr *errortypes.MultiError) {
	multiErr.AddOzzoError(validation.ValidateStruct(e,
		validation.Field(&e.OrganizationID, validation.Required),
		validation.Field(&e.BusinessUnitID, validation.Required),
		validation.Field(&e.FiscalYearID, validation.Required),
		validation.Field(&e.FiscalPeriodID, validation.Required),
		validation.Field(&e.EntryNumber, validation.Required, validation.Length(1, 50)),
		validation.Field(&e.Description, validation.Required),
		validation.Field(&e.CreatedByID, validation.Required),
	))

	if !e.EntryType.IsValid() {
		multiErr.Add("entryType", errortypes.ErrInvalid, "Entry type is invalid")
	}
	if !e.Status.IsValid() {
		multiErr.Add("status", errortypes.ErrInvalid, "Status is invalid")
	}
	if e.Status != StatusDraft && e.TotalDebit != e.TotalCredit {
		multiErr.Add(
			"totalDebit",
			errortypes.ErrInvalid,
			"Total debit must equal total credit outside of draft",
		)
	}
	if e.IsReversal && e.ReversalOfID.IsNil() {
		multiErr.Add(
			"reversalOfId",
			errortypes.ErrRequired,
			"A reversal must name the entry it reverses",
		)
	}
	for idx, line := range e.Lines {
		if line == nil {
			multiErr.Add("lines", errortypes.ErrInvalid, "Lines must not contain null values")
			continue
		}
		line.Validate(multiErr.WithIndex("lines", idx))
	}
}

func (l *JournalEntryLine) Validate(multiErr *errortypes.MultiError) {
	multiErr.AddOzzoError(validation.ValidateStruct(l,
		validation.Field(&l.OrganizationID, validation.Required),
		validation.Field(&l.BusinessUnitID, validation.Required),
		validation.Field(&l.GLAccountID, validation.Required),
		validation.Field(&l.Description, validation.Required),
	))

	if l.DebitAmount < 0 || l.CreditAmount < 0 {
		multiErr.Add("debitAmount", errortypes.ErrInvalid, "Amounts cannot be negative")
	}
	if (l.DebitAmount == 0) == (l.CreditAmount == 0) {
		multiErr.Add(
			"debitAmount",
			errortypes.ErrInvalid,
			"A line must carry either a debit or a credit, not both and not neither",
		)
	}
}

func (e *JournalEntry) GetTableName() string { return "journal_entries" }

func (e *JournalEntry) GetID() pulid.ID { return e.ID }

func (e *JournalEntry) GetCreatedAt() int64 { return e.CreatedAt }

func (e *JournalEntry) GetOrganizationID() pulid.ID { return e.OrganizationID }

func (e *JournalEntry) GetBusinessUnitID() pulid.ID { return e.BusinessUnitID }

func (e *JournalEntry) CanReverse() bool {
	return e != nil && e.Status == StatusPosted && e.ReversedByID.IsNil()
}

func (e *JournalEntry) GetPostgresSearchConfig() domaintypes.PostgresSearchConfig {
	return domaintypes.PostgresSearchConfig{
		TableAlias:      "je",
		UseSearchVector: true,
		SearchableFields: []domaintypes.SearchableField{
			{
				Name:   "entry_number",
				Type:   domaintypes.FieldTypeText,
				Weight: domaintypes.SearchWeightA,
			},
			{
				Name:   "reference_number",
				Type:   domaintypes.FieldTypeText,
				Weight: domaintypes.SearchWeightA,
			},
			{
				Name:   "description",
				Type:   domaintypes.FieldTypeText,
				Weight: domaintypes.SearchWeightB,
			},
			{Name: "status", Type: domaintypes.FieldTypeEnum},
			{Name: "entry_type", Type: domaintypes.FieldTypeEnum},
		},
	}
}

func (l *JournalEntryLine) GetTableName() string { return "journal_entry_lines" }

func (l *JournalEntryLine) GetID() pulid.ID { return l.ID }

func (l *JournalEntryLine) GetCreatedAt() int64 { return l.CreatedAt }

func (e *JournalEntry) BeforeCreate(ctx context.Context) error {
	if e.EntryType == "" {
		e.EntryType = EntryTypeStandard
	}
	if e.Status == "" {
		e.Status = StatusDraft
	}

	return nil
}
