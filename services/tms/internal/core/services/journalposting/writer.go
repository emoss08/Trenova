package journalposting

import (
	"context"

	"github.com/emoss08/trenova/internal/core/domain/fiscalperiod"
	"github.com/emoss08/trenova/internal/core/domain/tenant"
	"github.com/emoss08/trenova/internal/core/ports/repositories"
	"github.com/emoss08/trenova/pkg/errortypes"
	"github.com/emoss08/trenova/shared/pulid"
)

type Numberer interface {
	GenerateJournalBatchNumber(
		ctx context.Context,
		orgID, buID pulid.ID,
		locationCode, businessUnitCode string,
	) (string, error)
	GenerateJournalEntryNumber(
		ctx context.Context,
		orgID, buID pulid.ID,
		locationCode, businessUnitCode string,
	) (string, error)
}

type Writer struct {
	Periods  PeriodReader
	Numbers  Numberer
	Journals repositories.JournalPostingRepository
}

type Line struct {
	AccountID   pulid.ID
	Debit       int64
	Credit      int64
	CustomerID  pulid.ID
	Description string
}

type Source struct {
	ObjectType     string
	ObjectID       pulid.ID
	DocumentNumber string
	Event          tenant.JournalSourceEventType
	IdempotencyKey string
}

type WriteRequest struct {
	OrganizationID pulid.ID
	BusinessUnitID pulid.ID
	Control        *tenant.AccountingControl
	ActorID        pulid.ID
	AccountingDate int64
	Now            int64
	Subject        string
	DateField      string
	Description    string
	Source         Source
	EntryType      string
	Reference      Reference
	AutoGenerated  bool
	Lines          []Line
}

type Reference struct {
	Type string
	ID   pulid.ID
}

type Plan struct {
	Period         *fiscalperiod.FiscalPeriod
	AccountingDate int64
	Workflow       Workflow
	Lines          []repositories.JournalPostingLine
	TotalDebit     int64
	TotalCredit    int64
}

type WriteResult struct {
	BatchID        pulid.ID
	EntryID        pulid.ID
	FiscalPeriodID pulid.ID
	AccountingDate int64
	Workflow       Workflow
}

func (w Writer) Plan(ctx context.Context, req *WriteRequest) (*Plan, error) {
	lines, totalDebit, totalCredit, err := buildLines(req)
	if err != nil {
		return nil, err
	}

	resolved, err := ResolvePeriod(ctx, w.Periods, &ResolvePeriodRequest{
		OrganizationID: req.OrganizationID,
		BusinessUnitID: req.BusinessUnitID,
		Date:           req.AccountingDate,
		Policy:         closedPeriodPolicy(req.Control),
		Subject:        req.Subject,
		Field:          req.DateField,
	})
	if err != nil {
		return nil, err
	}

	return &Plan{
		Period:         resolved.Period,
		AccountingDate: resolved.AccountingDate,
		Workflow:       ResolveWorkflow(req.Control, req.ActorID, req.Now),
		Lines:          lines,
		TotalDebit:     totalDebit,
		TotalCredit:    totalCredit,
	}, nil
}

func (w Writer) Write(ctx context.Context, req *WriteRequest) (*WriteResult, error) {
	plan, err := w.Plan(ctx, req)
	if err != nil {
		return nil, err
	}
	return w.WritePlan(ctx, req, plan)
}

func (w Writer) WritePlan(
	ctx context.Context,
	req *WriteRequest,
	plan *Plan,
) (*WriteResult, error) {
	batchNumber, err := w.Numbers.GenerateJournalBatchNumber(
		ctx, req.OrganizationID, req.BusinessUnitID, "", "")
	if err != nil {
		return nil, err
	}
	entryNumber, err := w.Numbers.GenerateJournalEntryNumber(
		ctx, req.OrganizationID, req.BusinessUnitID, "", "")
	if err != nil {
		return nil, err
	}

	workflow := plan.Workflow
	result := &WriteResult{
		BatchID:        pulid.MustNew("jb_"),
		EntryID:        pulid.MustNew("je_"),
		FiscalPeriodID: plan.Period.ID,
		AccountingDate: plan.AccountingDate,
		Workflow:       workflow,
	}
	event := req.Source.Event.String()
	if err = w.Journals.CreatePosting(ctx, repositories.CreateJournalPostingParams{
		BatchID:              result.BatchID,
		OrganizationID:       req.OrganizationID,
		BusinessUnitID:       req.BusinessUnitID,
		BatchNumber:          batchNumber,
		BatchType:            "System",
		BatchStatus:          workflow.BatchStatus,
		BatchDescription:     req.Description,
		FiscalYearID:         plan.Period.FiscalYearID,
		FiscalPeriodID:       plan.Period.ID,
		AccountingDate:       plan.AccountingDate,
		PostedAt:             workflow.PostedAt,
		PostedByID:           workflow.PostedByID,
		CreatedByID:          req.ActorID,
		UpdatedByID:          req.ActorID,
		EntryID:              result.EntryID,
		EntryNumber:          entryNumber,
		EntryType:            req.entryType(),
		EntryStatus:          workflow.EntryStatus,
		ReferenceNumber:      req.Source.DocumentNumber,
		ReferenceType:        req.referenceType(),
		ReferenceID:          req.referenceID().String(),
		EntryDescription:     req.Description,
		TotalDebit:           plan.TotalDebit,
		TotalCredit:          plan.TotalCredit,
		IsPosted:             workflow.Posted(),
		IsAutoGenerated:      req.AutoGenerated,
		RequiresApproval:     workflow.RequiresApproval,
		IsApproved:           workflow.IsApproved,
		ApprovedByID:         workflow.ApprovedByID,
		ApprovedAt:           workflow.ApprovedAt,
		SourceID:             pulid.MustNew("jsrc_"),
		SourceObjectType:     req.Source.ObjectType,
		SourceObjectID:       req.Source.ObjectID.String(),
		SourceEventType:      event,
		SourceStatus:         workflow.EntryStatus,
		SourceDocumentNumber: req.Source.DocumentNumber,
		SourceIdempotencyKey: req.Source.IdempotencyKey,
		Lines:                plan.Lines,
	}); err != nil {
		return nil, err
	}

	return result, nil
}

func buildLines(
	req *WriteRequest,
) (lines []repositories.JournalPostingLine, totalDebit, totalCredit int64, err error) {
	lines = make([]repositories.JournalPostingLine, 0, len(req.Lines))
	for idx, line := range req.Lines {
		if line.AccountID.IsNil() || line.Debit < 0 || line.Credit < 0 ||
			(line.Debit == 0) == (line.Credit == 0) {
			return nil, 0, 0, errortypes.NewBusinessError(
				"Every line of the " + req.Subject + " journal needs an account and one positive side",
			)
		}
		description := line.Description
		if description == "" {
			description = req.Description
		}
		totalDebit += line.Debit
		totalCredit += line.Credit
		lines = append(lines, repositories.JournalPostingLine{
			ID:           pulid.MustNew("jel_"),
			GLAccountID:  line.AccountID,
			LineNumber:   int16(idx + 1),
			Description:  description,
			DebitAmount:  line.Debit,
			CreditAmount: line.Credit,
			NetAmount:    line.Debit - line.Credit,
			CustomerID:   line.CustomerID,
		})
	}
	if len(lines) < 2 || totalDebit != totalCredit {
		return nil, 0, 0, errortypes.NewBusinessError(
			"The " + req.Subject + " journal does not balance",
		)
	}
	return lines, totalDebit, totalCredit, nil
}

func closedPeriodPolicy(control *tenant.AccountingControl) tenant.ClosedPeriodPostingPolicy {
	if control == nil {
		return tenant.ClosedPeriodPostingPolicyRequireReopen
	}
	return control.ClosedPeriodPostingPolicy
}

func (req *WriteRequest) entryType() string {
	if req.EntryType == "" {
		return "Standard"
	}
	return req.EntryType
}

func (req *WriteRequest) referenceType() string {
	if req.Reference.Type == "" {
		return req.Source.Event.String()
	}
	return req.Reference.Type
}

func (req *WriteRequest) referenceID() pulid.ID {
	if req.Reference.ID.IsNil() {
		return req.Source.ObjectID
	}
	return req.Reference.ID
}
