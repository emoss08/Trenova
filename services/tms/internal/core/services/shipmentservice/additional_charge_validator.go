package shipmentservice

import (
	"context"
	"fmt"

	"github.com/emoss08/trenova/internal/core/domain/shipment"
	"github.com/emoss08/trenova/internal/core/ports/repositories"
	"github.com/emoss08/trenova/pkg/errortypes"
	"github.com/emoss08/trenova/pkg/validationframework"
	"github.com/emoss08/trenova/shared/pulid"
)

type additionalChargeRuleContext struct {
	index                 int
	charge                *shipment.AdditionalCharge
	shipmentID            pulid.ID
	isCreate              bool
	seenChargeIDs         map[pulid.ID]string
	autoDetentionChargeID *pulid.ID
	multiErr              *errortypes.MultiError
}

func createAdditionalChargeValidationRule(
	controlRepo repositories.ShipmentControlRepository,
) validationframework.TenantedRule[*shipment.Shipment] {
	return validationframework.
		NewTenantedRule[*shipment.Shipment]("shipment_additional_charge_validation").
		OnBoth().
		WithStage(validationframework.ValidationStageDataIntegrity).
		WithPriority(validationframework.ValidationPriorityHigh).
		WithValidation(func(
			ctx context.Context,
			entity *shipment.Shipment,
			valCtx *validationframework.TenantedValidationContext,
			multiErr *errortypes.MultiError,
		) error {
			seenChargeIDs := make(map[pulid.ID]string, len(entity.AdditionalCharges))
			autoDetentionChargeID := autoGeneratedDetentionChargeID(ctx, controlRepo, entity)

			for index, charge := range entity.AdditionalCharges {
				if charge == nil {
					continue
				}

				charge.Validate(multiErr.WithIndex("additionalCharges", index))

				ruleCtx := additionalChargeRuleContext{
					index:                 index,
					charge:                charge,
					shipmentID:            entity.ID,
					isCreate:              valCtx.IsCreate(),
					seenChargeIDs:         seenChargeIDs,
					autoDetentionChargeID: autoDetentionChargeID,
					multiErr:              multiErr,
				}

				validateAdditionalChargeIdentifiers(ruleCtx)
				validateAdditionalChargeNotAutoGenerated(ruleCtx)
			}

			return nil
		})
}

// autoGeneratedDetentionChargeID reports the accessorial the organization bills
// detention with, but only while detention charges are generated automatically.
// A nil result means nothing is auto-generated and every charge may be entered
// by hand. Control lookup failures are reported by the control policy rule, so
// this deliberately degrades to "no restriction" instead of double-reporting.
func autoGeneratedDetentionChargeID(
	ctx context.Context,
	controlRepo repositories.ShipmentControlRepository,
	entity *shipment.Shipment,
) *pulid.ID {
	control, err := loadShipmentControlForValidation(ctx, controlRepo, entity)
	if err != nil || control == nil {
		return nil
	}

	if !control.TrackDetentionTime ||
		!control.AutoGenerateDetentionCharges ||
		control.DetentionChargeID == nil ||
		control.DetentionChargeID.IsNil() {
		return nil
	}

	return control.DetentionChargeID
}

// validateAdditionalChargeNotAutoGenerated stops a user from hand-entering the
// detention accessorial the system already bills, which would double-charge the
// customer for the same dwell time. The system's own detention line carries
// IsSystemGenerated and is reconciled on every save, so it is left alone.
func validateAdditionalChargeNotAutoGenerated(ctx additionalChargeRuleContext) {
	if ctx.autoDetentionChargeID == nil || ctx.charge.IsSystemGenerated {
		return
	}
	if ctx.charge.AccessorialChargeID != *ctx.autoDetentionChargeID {
		return
	}

	ctx.multiErr.Add(
		additionalChargeFieldPath(ctx.index, "accessorialChargeId"),
		errortypes.ErrInvalid,
		"Detention charges are generated automatically and cannot be added manually",
	)
}

func validateAdditionalChargeIdentifiers(ctx additionalChargeRuleContext) {
	if ctx.isCreate {
		if !ctx.charge.ID.IsNil() {
			ctx.multiErr.Add(
				additionalChargeFieldPath(ctx.index, "id"),
				errortypes.ErrInvalid,
				"Additional charge ID must not be provided when creating a shipment",
			)
		}
		if !ctx.charge.ShipmentID.IsNil() {
			ctx.multiErr.Add(
				additionalChargeFieldPath(ctx.index, "shipmentId"),
				errortypes.ErrInvalid,
				"Additional charge shipment ID must not be provided when creating a shipment",
			)
		}
	} else if !ctx.shipmentID.IsNil() &&
		!ctx.charge.ShipmentID.IsNil() &&
		ctx.charge.ShipmentID != ctx.shipmentID {
		ctx.multiErr.Add(
			additionalChargeFieldPath(ctx.index, "shipmentId"),
			errortypes.ErrInvalid,
			"Additional charge shipment ID must match the shipment being updated",
		)
	}

	if ctx.charge.ID.IsNil() {
		return
	}

	currentPath := additionalChargeFieldPath(ctx.index, "id")
	if firstPath, ok := ctx.seenChargeIDs[ctx.charge.ID]; ok {
		ctx.multiErr.Add(
			currentPath,
			errortypes.ErrDuplicate,
			fmt.Sprintf("Additional charge ID duplicates %s", firstPath),
		)
		return
	}

	ctx.seenChargeIDs[ctx.charge.ID] = currentPath
}

func additionalChargeFieldPath(index int, field string) string {
	return fmt.Sprintf("additionalCharges[%d].%s", index, field)
}
