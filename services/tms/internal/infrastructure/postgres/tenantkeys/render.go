package tenantkeys

import (
	"errors"
	"fmt"
	"slices"
	"strings"
)

const (
	actionNoAction   = "a"
	actionRestrict   = "r"
	actionCascade    = "c"
	actionSetNull    = "n"
	actionSetDefault = "d"
	matchFull        = "f"

	IndexesMigration   = "tenant_key_indexes"
	AddedMigration     = "tenant_keys_added"
	ValidatedMigration = "tenant_keys_validated"
	SwappedMigration   = "tenant_keys_swapped"
)

var ErrUnsupported = errors.New("these foreign keys cannot be converted by the generator")

type Migration struct {
	Name string
	SQL  string
}

func (m Migration) File(version string) string {
	return version + "_" + m.Name + ".sql"
}

func quote(name string) string {
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

func literal(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

func quoteAll(names []string) string {
	out := make([]string, 0, len(names))
	for _, n := range names {
		out = append(out, quote(n))
	}
	return strings.Join(out, ", ")
}

func Render(inv *Inventory) ([]Migration, error) {
	if len(inv.Unsupported) > 0 {
		return nil, fmt.Errorf("%w:\n  %s", ErrUnsupported, strings.Join(inv.Unsupported, "\n  "))
	}
	out := make([]Migration, 0, 4)
	if sql := renderIndexes(inv); sql != "" {
		out = append(out, Migration{Name: IndexesMigration, SQL: sql})
	}
	keys := inv.Of(ClassConvertible)
	if len(keys) == 0 {
		return out, nil
	}
	return append(out,
		Migration{Name: AddedMigration, SQL: renderAdded(keys)},
		Migration{Name: ValidatedMigration, SQL: renderValidated(keys)},
		Migration{Name: SwappedMigration, SQL: renderSwapped(keys)},
	), nil
}

const indexesHeader = `--keel:notx
-- Every foreign key between tenant tables gets an index whose leading columns are its own
-- reference columns (or its whole key), so PostgreSQL's delete checks and a tenant removal never
-- scan every tenant's rows of the referring table. A unique index on (id, <tenant column>) of each
-- parent lets the next migration's keys carry the tenant. Generated by the tenantkeys catalog
-- test (internal/infrastructure/postgres/tenantkeys); see docs/engineering/backend/data-access.md.
`

func renderIndexes(inv *Inventory) string {
	parts := make([]string, 0, len(inv.Uniques)+len(inv.Indexes))
	for _, u := range inv.Uniques {
		parts = append(parts, fmt.Sprintf(
			"CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS %s\n    ON %s(%s);",
			quote(u.Name), quote(u.Table), quoteAll(u.Columns)))
	}
	for _, idx := range inv.Indexes {
		stmt := fmt.Sprintf("CREATE INDEX CONCURRENTLY IF NOT EXISTS %s\n    ON %s(%s)",
			quote(idx.Name), quote(idx.Table), quoteAll(idx.Columns))
		if idx.Predicate != "" {
			stmt += "\n    WHERE " + predicateSQL(idx.Columns, idx.Predicate)
		}
		parts = append(parts, stmt+";")
	}
	if len(parts) == 0 {
		return ""
	}
	return indexesHeader + strings.Join(parts, "\n--keel:split\n") + "\n"
}

func predicateSQL(columns []string, predicate string) string {
	conds := make([]string, 0, len(columns))
	for _, c := range columns {
		if strings.Contains(predicate, "("+c+" IS NOT NULL)") {
			conds = append(conds, quote(c)+" IS NOT NULL")
		}
	}
	return strings.Join(conds, " AND ")
}

const addedHeader = `-- A foreign key that names a record by id alone is not held to the row's tenant: a foreign-key
-- check ignores row-level security, so a write that carried another tenant's id passed it. Each
-- such key between tenant tables is added again carrying the row's business unit (or, where a
-- table has no business unit, its organization), NOT VALID so no table is scanned under its
-- lock; the next migration validates them and the one after drops the old keys and gives the new
-- ones their names. Before anything is added, every row that already refers to a record of
-- another tenant is counted, and the migration stops with each table, column and count rather
-- than adding keys the data breaks. Generated by the tenantkeys catalog test.

`

func renderAdded(keys []*Key) string {
	var b strings.Builder
	b.WriteString(addedHeader)
	b.WriteString(renderPreflight(keys))
	for _, group := range byChild(keys) {
		adds := make([]string, 0, len(group))
		for _, k := range group {
			adds = append(adds, "    ADD CONSTRAINT "+quote(TemporaryName(k.FK.Name))+
				" FOREIGN KEY ("+quoteAll(k.Columns())+") REFERENCES "+quote(k.FK.Parent)+
				"("+quoteAll(k.ParentColumns())+")"+actions(k.FK)+" NOT VALID")
		}
		b.WriteString("\nALTER TABLE " + quote(group[0].FK.Child) + "\n" +
			strings.Join(adds, ",\n") + ";\n")
	}
	return b.String()
}

func renderPreflight(keys []*Key) string {
	rows := make([]string, 0, len(keys))
	for _, k := range slices.Concat(byChild(keys)...) {
		rows = append(rows, fmt.Sprintf("        (%s, ARRAY[%s], %s, ARRAY[%s], %s, %s)",
			literal(k.FK.Child), literals(k.FK.ChildColumns), literal(k.FK.Parent),
			literals(k.FK.ParentColumns), literal(k.Form.Child), literal(k.Form.Parent)))
	}
	return `DO $preflight$
DECLARE
    k record;
    present text;
    matched text;
    found bigint;
    problems text := '';
BEGIN
    FOR k IN
        SELECT * FROM (VALUES
` + strings.Join(rows, ",\n") + `
        ) AS v(child, child_columns, parent, parent_columns, child_tenant, parent_tenant)
    LOOP
        SELECT string_agg(format('c.%I IS NOT NULL', u.c), ' AND '),
               string_agg(format('p.%I = c.%I', u.p, u.c), ' AND ')
        INTO present, matched
        FROM unnest(k.child_columns, k.parent_columns) AS u(c, p);
        EXECUTE format(
            'SELECT count(*) FROM %I c WHERE %s AND NOT EXISTS (SELECT 1 FROM %I p WHERE %s AND p.%I = c.%I)',
            k.child, present, k.parent, matched, k.parent_tenant, k.child_tenant
        ) INTO found;
        IF found > 0 THEN
            problems := problems || format(E'\n  %s.%s: %s rows refer to a %s row of another tenant',
                k.child, array_to_string(k.child_columns, ', '), found, k.parent);
        END IF;
    END LOOP;
    IF problems <> '' THEN
        RAISE EXCEPTION 'rows refer to records of another tenant, so their foreign keys cannot carry the tenant; nothing was changed:%', problems
            USING HINT = 'Point each reference at a record of the row''s own tenant or clear it, then run the migration again (docs/engineering/backend/data-access.md, "Tenant keys").';
    END IF;
END
$preflight$;
`
}

func literals(values []string) string {
	out := make([]string, 0, len(values))
	for _, v := range values {
		out = append(out, literal(v))
	}
	return strings.Join(out, ", ")
}

func actions(fk *ForeignKey) string {
	var b strings.Builder
	b.WriteString(" ON UPDATE " + simpleAction(fk.OnUpdate))
	b.WriteString(" ON DELETE " + deleteAction(fk))
	if fk.Deferrable {
		b.WriteString(" DEFERRABLE")
		if fk.Deferred {
			b.WriteString(" INITIALLY DEFERRED")
		}
	}
	return b.String()
}

func simpleAction(code string) string {
	switch code {
	case actionNoAction:
		return "NO ACTION"
	case actionRestrict:
		return "RESTRICT"
	case actionCascade:
		return "CASCADE"
	case actionSetNull:
		return "SET NULL"
	case actionSetDefault:
		return "SET DEFAULT"
	default:
		return "NO ACTION"
	}
}

func deleteAction(fk *ForeignKey) string {
	switch fk.OnDelete {
	case actionSetNull, actionSetDefault:
		columns := fk.SetColumns
		if len(columns) == 0 {
			columns = fk.ChildColumns
		}
		return simpleAction(fk.OnDelete) + " (" + quoteAll(columns) + ")"
	default:
		return simpleAction(fk.OnDelete)
	}
}

func byChild(keys []*Key) [][]*Key {
	groups := make(map[string][]*Key)
	order := make([]string, 0)
	for _, k := range keys {
		if _, ok := groups[k.FK.Child]; !ok {
			order = append(order, k.FK.Child)
		}
		groups[k.FK.Child] = append(groups[k.FK.Child], k)
	}
	slices.Sort(order)
	out := make([][]*Key, 0, len(order))
	for _, child := range order {
		group := groups[child]
		slices.SortFunc(group, func(a, b *Key) int { return strings.Compare(a.FK.Name, b.FK.Name) })
		out = append(out, group)
	}
	return out
}

const validatedHeader = `-- Validates the tenant-carrying foreign keys the previous migration added NOT VALID. VALIDATE
-- CONSTRAINT holds SHARE UPDATE EXCLUSIVE on the referring table and ROW SHARE on the referenced
-- one, so reads and writes go on while each table is checked. Generated by the tenantkeys
-- catalog test.

`

func renderValidated(keys []*Key) string {
	var b strings.Builder
	b.WriteString(validatedHeader)
	for _, group := range byChild(keys) {
		for _, k := range group {
			b.WriteString("ALTER TABLE " + quote(k.FK.Child) + " VALIDATE CONSTRAINT " +
				quote(TemporaryName(k.FK.Name)) + ";\n")
		}
	}
	return b.String()
}

const swappedHeader = `-- Drops each foreign key that named a record by id alone and gives its tenant-carrying
-- replacement the old name, so every model's constraint messages and every constraint lookup in
-- the code keep working. Each statement holds ACCESS EXCLUSIVE on the two tables for an instant
-- (no scan). Generated by the tenantkeys catalog test.

`

func renderSwapped(keys []*Key) string {
	var b strings.Builder
	b.WriteString(swappedHeader)
	for _, group := range byChild(keys) {
		drops := make([]string, 0, len(group))
		for _, k := range group {
			drops = append(drops, "    DROP CONSTRAINT "+quote(k.FK.Name))
		}
		b.WriteString(
			"ALTER TABLE " + quote(group[0].FK.Child) + "\n" + strings.Join(drops, ",\n") +
				";\n",
		)
		for _, k := range group {
			b.WriteString("ALTER TABLE " + quote(k.FK.Child) + " RENAME CONSTRAINT " +
				quote(TemporaryName(k.FK.Name)) + " TO " + quote(k.FK.Name) + ";\n")
		}
		b.WriteString("\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}
