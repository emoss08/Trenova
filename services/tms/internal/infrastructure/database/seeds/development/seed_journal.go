type seedJournalLeg struct {
	AccountID  pulid.ID
	Debit      int64
	Credit     int64
	CustomerID pulid.ID
}

type seedJournalRequest struct {
	seedName       string
	orgID          pulid.ID
	buID           pulid.ID
	actorID        pulid.ID
	accountingDate int64
	batchNumber    string
	entryNumber    string
	description    string
	sourceType     string
	sourceID       string
	documentNumber string
	event          string
	idempotencyKey string
	autoGenerated  bool
	legs           []seedJournalLeg
}

type seedJournalResult struct {
	batchID pulid.ID
	entryID pulid.ID
}

type seedFiscalPeriod struct {
	ID           pulid.ID `bun:"id"`
	FiscalYearID pulid.ID `bun:"fiscal_year_id"`
}

func postSeedJournal(
	ctx context.Context,
	tx bun.Tx,
	sc *seedhelpers.SeedContext,
	req *seedJournalRequest,
) (*seedJournalResult, error) {
	var period seedFiscalPeriod
	if err := tx.NewSelect().Table("fiscal_periods").Column("id", "fiscal_year_id").
		Where("organization_id = ?", req.orgID).
		Where("business_unit_id = ?", req.buID).
		Where("start_date <= ?", req.accountingDate).
		Where("end_date >= ?", req.accountingDate).
		Limit(1).
		Scan(ctx, &period); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, errSeedNoFiscalPeriod
		}
		return nil, fmt.Errorf("get fiscal period: %w", err)
	}

	result := &seedJournalResult{batchID: pulid.MustNew("jb_"), entryID: pulid.MustNew("je_")}
	sourceID := pulid.MustNew("jsrc_")
	date := req.accountingDate

	var totalDebit, totalCredit int64
	lines := make([]*seedJournalEntryLine, 0, len(req.legs))
	for idx, leg := range req.legs {
		totalDebit += leg.Debit
		totalCredit += leg.Credit
		lines = append(lines, &seedJournalEntryLine{
			ID:             pulid.MustNew("jel_"),
			BusinessUnitID: req.buID,
			OrganizationID: req.orgID,
			JournalEntryID: result.entryID,
			GLAccountID:    leg.AccountID,
			LineNumber:     int16(idx + 1), //nolint:gosec // bounded by leg count
			Description:    req.description,
			DebitAmount:    leg.Debit,
			CreditAmount:   leg.Credit,
			NetAmount:      leg.Debit - leg.Credit,
			CustomerID:     leg.CustomerID,
		})
	}
	if totalDebit != totalCredit {
		return nil, fmt.Errorf("journal for %s does not balance: %d debit, %d credit",
			req.documentNumber, totalDebit, totalCredit)
	}

	batch := &seedJournalBatch{
		ID:             result.batchID,
		OrganizationID: req.orgID,
		BusinessUnitID: req.buID,
		BatchNumber:    req.batchNumber,
		BatchType:      "System",
		Status:         "Posted",
		Description:    req.description,
		AccountingDate: date,
		FiscalYearID:   period.FiscalYearID,
		FiscalPeriodID: period.ID,
		EntryCount:     1,
		PostedAt:       &date,
		PostedByID:     req.actorID,
		CreatedByID:    req.actorID,
		UpdatedByID:    req.actorID,
	}
	entry := &seedJournalEntry{
		ID:              result.entryID,
		BusinessUnitID:  req.buID,
		OrganizationID:  req.orgID,
		BatchID:         result.batchID,
		FiscalYearID:    period.FiscalYearID,
		FiscalPeriodID:  period.ID,
		EntryNumber:     req.entryNumber,
		EntryDate:       date,
		EntryType:       "Standard",
		AccountingDate:  date,
		Status:          "Posted",
		ReferenceNumber: req.documentNumber,
		ReferenceType:   req.event,
		ReferenceID:     req.sourceID,
		Description:     req.description,
		TotalDebit:      totalDebit,
		TotalCredit:     totalCredit,
		IsPosted:        true,
		PostedAt:        &date,
		PostedByID:      req.actorID,
		IsAutoGenerated: req.autoGenerated,
		IsApproved:      true,
		ApprovedAt:      &date,
		ApprovedByID:    req.actorID,
		CreatedByID:     req.actorID,
		UpdatedByID:     req.actorID,
	}
	source := &seedJournalSource{
		ID:                   sourceID,
		BusinessUnitID:       req.buID,
		OrganizationID:       req.orgID,
		SourceObjectType:     req.sourceType,
		SourceObjectID:       req.sourceID,
		SourceEventType:      req.event,
		SourceDocumentNumber: req.documentNumber,
		Status:               "Posted",
		IdempotencyKey:       req.idempotencyKey,
		JournalBatchID:       result.batchID,
		JournalEntryID:       result.entryID,
	}
	link := &seedSourceJournalLink{
		ID:              sourceID,
		BusinessUnitID:  req.buID,
		OrganizationID:  req.orgID,
		JournalSourceID: sourceID,
		JournalBatchID:  result.batchID,
		JournalEntryID:  result.entryID,
		LinkRole:        "Primary",
	}

	if err := insertSeedRow(ctx, tx, sc, req.seedName, "journal_batches", batch.ID, batch); err != nil {
		return nil, err
	}
	if err := insertSeedRow(ctx, tx, sc, req.seedName, "journal_entries", entry.ID, entry); err != nil {
		return nil, err
	}
	if err := insertSeedJournalLines(ctx, tx, sc, req.seedName, lines); err != nil {
		return nil, err
	}
	if err := insertSeedRow(ctx, tx, sc, req.seedName, "journal_sources", source.ID, source); err != nil {
		return nil, err
	}
	if err := insertSeedRow(
		ctx, tx, sc, req.seedName, "source_journal_links", link.ID, link,
	); err != nil {
		return nil, err
	}

	for _, line := range lines {
		if err := applySeedJournalBalance(ctx, tx, req, &period, result.entryID, line); err != nil {
			return nil, err
		}
	}

	return result, nil
}

func insertSeedJournalLines(
	ctx context.Context,
	tx bun.Tx,
	sc *seedhelpers.SeedContext,
	seedName string,
	lines []*seedJournalEntryLine,
) error {
	if _, err := tx.NewInsert().Model(&lines).Exec(ctx); err != nil {
		return fmt.Errorf("insert journal entry lines: %w", err)
	}
	for _, line := range lines {
		if err := sc.TrackCreated(ctx, "journal_entry_lines", line.ID, seedName); err != nil {
			return fmt.Errorf("track journal entry line: %w", err)
		}
	}

	return nil
}

func applySeedJournalBalance(
	ctx context.Context,
	tx bun.Tx,
	req *seedJournalRequest,
	period *seedFiscalPeriod,
	entryID pulid.ID,
	line *seedJournalEntryLine,
) error {
	if _, err := tx.NewRaw(`
		INSERT INTO gl_account_balances_by_period AS gb (
			organization_id,
			business_unit_id,
			gl_account_id,
			fiscal_year_id,
			fiscal_period_id,
			period_debit_minor,
			period_credit_minor,
			net_change_minor,
			last_journal_entry_id
		) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
		ON CONFLICT (organization_id, business_unit_id, gl_account_id, fiscal_year_id, fiscal_period_id)
		DO UPDATE SET
			period_debit_minor = gb.period_debit_minor + EXCLUDED.period_debit_minor,
			period_credit_minor = gb.period_credit_minor + EXCLUDED.period_credit_minor,
			net_change_minor = gb.net_change_minor + EXCLUDED.net_change_minor,
			last_journal_entry_id = EXCLUDED.last_journal_entry_id,
			updated_at = `+dbhelper.NowEpoch+`
	`,
		req.orgID, req.buID, line.GLAccountID, period.FiscalYearID, period.ID,
		line.DebitAmount, line.CreditAmount, line.NetAmount, entryID,
	).Exec(ctx); err != nil {
		return fmt.Errorf("upsert gl balance by period: %w", err)
	}

	if _, err := tx.NewUpdate().Table("gl_accounts").
		Set("current_balance = current_balance + ?", line.NetAmount).
		Set("debit_balance = debit_balance + ?", line.DebitAmount).
		Set("credit_balance = credit_balance + ?", line.CreditAmount).
		Set("updated_at = "+dbhelper.NowEpoch).
		Where("id = ?", line.GLAccountID).
		Where("organization_id = ?", req.orgID).
		Where("business_unit_id = ?", req.buID).
		Exec(ctx); err != nil {
		return fmt.Errorf("update gl account running balance: %w", err)
	}

	return nil
}
