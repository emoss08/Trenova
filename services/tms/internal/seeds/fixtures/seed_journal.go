var errSeedNoFiscalPeriod = errors.New("no fiscal period covers the accounting date")

type seedJournalLeg struct {
	AccountID  pulid.ID
	Debit      int64
	Credit     int64
	CustomerID pulid.ID
}

type seedJournalRequest struct {
	orgID          pulid.ID
	buID           pulid.ID
	actorID        pulid.ID
	accountingDate int64
	batchNumber    string
	entryNumber    string
	description    string
	sourceType     string
	sourceID       string
	documentNumber string
	event          string
	idempotencyKey string
	autoGenerated  bool
	legs           []seedJournalLeg
}

type seedJournalResult struct {
	batchID pulid.ID
	entryID pulid.ID
}

type seedAccountMovement struct {
	accountID pulid.ID
	debit     int64
	credit    int64
}

func postSeedJournal(
	ctx context.Context,
	db *keel.DB,
	req *seedJournalRequest,
) (*seedJournalResult, error) {
	period, err := seedFiscalPeriodFor(ctx, db, req)
	if err != nil {
		return nil, err
	}

	result := &seedJournalResult{batchID: pulid.MustNew("jb_"), entryID: pulid.MustNew("je_")}
	date := req.accountingDate

	var totalDebit, totalCredit int64
	lines := make([]*journalentry.JournalEntryLine, 0, len(req.legs))
	for idx, leg := range req.legs {
		totalDebit += leg.Debit
		totalCredit += leg.Credit
		lines = append(lines, &journalentry.JournalEntryLine{
			ID:             pulid.MustNew("jel_"),
			BusinessUnitID: req.buID,
			OrganizationID: req.orgID,
			JournalEntryID: result.entryID,
			GLAccountID:    leg.AccountID,
			LineNumber:     int16(idx + 1), //nolint:gosec // bounded by leg count
			Description:    req.description,
			DebitAmount:    leg.Debit,
			CreditAmount:   leg.Credit,
			NetAmount:      leg.Debit - leg.Credit,
			CustomerID:     leg.CustomerID,
		})
	}
	if totalDebit != totalCredit {
		return nil, fmt.Errorf("journal for %s does not balance: %d debit, %d credit",
			req.documentNumber, totalDebit, totalCredit)
	}

	batch := &journalentry.JournalBatch{
		ID:             result.batchID,
		OrganizationID: req.orgID,
		BusinessUnitID: req.buID,
		BatchNumber:    req.batchNumber,
		BatchType:      "System",
		Status:         string(journalentry.StatusPosted),
		Description:    req.description,
		AccountingDate: date,
		FiscalYearID:   period.FiscalYearID,
		FiscalPeriodID: period.ID,
		EntryCount:     1,
		PostedAt:       &date,
		PostedByID:     req.actorID,
		CreatedByID:    req.actorID,
		UpdatedByID:    req.actorID,
	}
	entry := &journalentry.JournalEntry{
		ID:              result.entryID,
		BusinessUnitID:  req.buID,
		OrganizationID:  req.orgID,
		BatchID:         result.batchID,
		FiscalYearID:    period.FiscalYearID,
		FiscalPeriodID:  period.ID,
		EntryNumber:     req.entryNumber,
		EntryDate:       date,
		EntryType:       journalentry.EntryTypeStandard,
		AccountingDate:  date,
		Status:          journalentry.StatusPosted,
		ReferenceNumber: req.documentNumber,
		ReferenceType:   req.event,
		ReferenceID:     req.sourceID,
		Description:     req.description,
		TotalDebit:      totalDebit,
		TotalCredit:     totalCredit,
		IsPosted:        true,
		PostedAt:        &date,
		PostedByID:      req.actorID,
		IsAutoGenerated: req.autoGenerated,
		IsApproved:      true,
		ApprovedAt:      &date,
		ApprovedByID:    req.actorID,
		CreatedByID:     req.actorID,
		UpdatedByID:     req.actorID,
	}
	source := &journalsource.Source{
		ID:                   pulid.MustNew("jsrc_"),
		BusinessUnitID:       req.buID,
		OrganizationID:       req.orgID,
		SourceObjectType:     req.sourceType,
		SourceObjectID:       req.sourceID,
		SourceEventType:      req.event,
		SourceDocumentNumber: req.documentNumber,
		Status:               string(journalentry.StatusPosted),
		IdempotencyKey:       req.idempotencyKey,
		JournalBatchID:       result.batchID,
		JournalEntryID:       result.entryID,
	}
	link := &journalsource.SourceJournalLink{
		BusinessUnitID:  req.buID,
		OrganizationID:  req.orgID,
		JournalSourceID: source.ID,
		JournalBatchID:  result.batchID,
		JournalEntryID:  result.entryID,
		LinkRole:        "Primary",
	}

	if err = journalentrydb.JournalBatches.Create(ctx, db, batch); err != nil {
		return nil, fmt.Errorf("insert journal batch: %w", err)
	}
	if err = journalentrydb.JournalEntries.Create(ctx, db, entry); err != nil {
		return nil, fmt.Errorf("insert journal entry: %w", err)
	}
	if err = journalentrydb.JournalEntryLines.CreateMany(ctx, db, lines); err != nil {
		return nil, fmt.Errorf("insert journal entry lines: %w", err)
	}
	if err = journalsourcedb.Sources.Create(ctx, db, source); err != nil {
		return nil, fmt.Errorf("insert journal source: %w", err)
	}
	if err = journalsourcedb.SourceJournalLinks.Create(ctx, db, link); err != nil {
		return nil, fmt.Errorf("insert source journal link: %w", err)
	}

	if err = applySeedJournalBalances(ctx, db, req, period, result.entryID, lines); err != nil {
		return nil, err
	}

	return result, nil
}

func seedFiscalPeriodFor(
	ctx context.Context,
	db *keel.DB,
	req *seedJournalRequest,
) (*fiscalperiod.FiscalPeriod, error) {
	fp := fiscalperioddb.FiscalPeriods
	period, err := fp.AllTenants().Pick(fp.ID, fp.FiscalYearID).Where(
		fp.OrganizationID.Eq(req.orgID),
		fp.BusinessUnitID.Eq(req.buID),
		fp.StartDate.Lte(req.accountingDate),
		fp.EndDate.Gte(req.accountingDate),
	).First(ctx, db)
	if errors.Is(err, keel.ErrNotFound) {
		return nil, errSeedNoFiscalPeriod
	}
	if err != nil {
		return nil, fmt.Errorf("get fiscal period: %w", err)
	}

	return period, nil
}

func seedAccountMovements(lines []*journalentry.JournalEntryLine) []seedAccountMovement {
	movements := make([]seedAccountMovement, 0, len(lines))
	index := make(map[pulid.ID]int, len(lines))
	for _, line := range lines {
		i, ok := index[line.GLAccountID]
		if !ok {
			i = len(movements)
			index[line.GLAccountID] = i
			movements = append(movements, seedAccountMovement{accountID: line.GLAccountID})
		}
		movements[i].debit += line.DebitAmount
		movements[i].credit += line.CreditAmount
	}

	return movements
}

func applySeedJournalBalances(
	ctx context.Context,
	db *keel.DB,
	req *seedJournalRequest,
	period *fiscalperiod.FiscalPeriod,
	entryID pulid.ID,
	lines []*journalentry.JournalEntryLine,
) error {
	movements := seedAccountMovements(lines)

	balances := make([]*glbalance.GLAccountPeriodBalance, 0, len(movements))
	for _, m := range movements {
		balances = append(balances, &glbalance.GLAccountPeriodBalance{
			OrganizationID:     req.orgID,
			BusinessUnitID:     req.buID,
			GLAccountID:        m.accountID,
			FiscalYearID:       period.FiscalYearID,
			FiscalPeriodID:     period.ID,
			PeriodDebitMinor:   m.debit,
			PeriodCreditMinor:  m.credit,
			NetChangeMinor:     m.debit - m.credit,
			LastJournalEntryID: entryID,
		})
	}

	b := glbalancedb.GLAccountPeriodBalances
	if _, err := b.Upsert(ctx, db, balances, keel.OnConflict(
		b.OrganizationID,
		b.BusinessUnitID,
		b.GLAccountID,
		b.FiscalYearID,
		b.FiscalPeriodID,
	).Set(
		b.PeriodDebitMinor.ToExpr(keel.Raw("? + ?", b.PeriodDebitMinor, b.PeriodDebitMinor.Excluded())),
		b.PeriodCreditMinor.ToExpr(
			keel.Raw("? + ?", b.PeriodCreditMinor, b.PeriodCreditMinor.Excluded()),
		),
		b.NetChangeMinor.ToExpr(keel.Raw("? + ?", b.NetChangeMinor, b.NetChangeMinor.Excluded())),
		b.LastJournalEntryID.ToExpr(b.LastJournalEntryID.Excluded()),
	),
	); err != nil {
		return fmt.Errorf("upsert gl balance by period: %w", err)
	}

	a := glaccountdb.GLAccounts
	for _, m := range movements {
		if _, err := a.AllTenants().Where(
			a.ID.Eq(m.accountID),
			a.OrganizationID.Eq(req.orgID),
			a.BusinessUnitID.Eq(req.buID),
		).Update(
			ctx,
			db,
			a.CurrentBalance.Add(m.debit-m.credit),
			a.DebitBalance.Add(m.debit),
			a.CreditBalance.Add(m.credit),
		); err != nil {
			return fmt.Errorf("update gl account running balance: %w", err)
		}
	}

	return nil
}
