package gqlext

import (
	"fmt"
	"slices"
	"strings"

	"github.com/emoss08/trenova/internal/modules/identity/domain/permission"
	"github.com/vektah/gqlparser/v2/ast"
)

const (
	// ReferenceFragmentsPath is where the generated reference fragments
	// live, relative to the repository root.
	ReferenceFragmentsPath = "client/packages/graphql/src/operations/reference/reference.graphql"
	// ReferenceViewsPath is the client's copy of every kind's reference
	// view, relative to the repository root.
	ReferenceViewsPath = "client/packages/shared/src/types/generated/reference-views.ts"

	referenceFragmentSuffix = "Reference"
	// clientPrintWidth is the client formatter's line width, so the
	// generated module is already formatted.
	clientPrintWidth = 100
)

// ReferenceFragmentName is the fragment a linking screen spreads to select a
// type's reference view, such as CustomerReference.
func ReferenceFragmentName(typeName string) string {
	return typeName + referenceFragmentSuffix
}

// referenceTypes is every kind type with a declared reference view, sorted,
// with the fields of its view that the type has. A type that has none of
// them, such as a summary of a kind's records, has no reference view.
func referenceTypes(
	schema *ast.Schema,
	registry *permission.Registry,
) (names []string, kinds map[string]permission.Resource, err error) {
	kinds, err = KindTypes(schema, registry)
	if err != nil {
		return nil, nil, err
	}
	names = make([]string, 0, len(kinds))
	for name, kind := range kinds {
		def, ok := registry.Get(kind.String())
		if !ok || len(def.ReferenceView) == 0 || !linkable(schema.Types[name], def.ReferenceView) {
			continue
		}
		if typ := schema.Types[name]; typ == nil || !slices.ContainsFunc(typ.Fields,
			func(field *ast.FieldDefinition) bool {
				return field.Name == recordIDField ||
					slices.Contains(def.ReferenceView, field.Name)
			}) {
			continue
		}
		names = append(names, name)
	}
	slices.Sort(names)

	return names, kinds, nil
}

// linkable reports whether a kind type is a record another can link to: it
// carries its id or a field of its kind's reference view. A detail or a
// summary of a kind (a message's detail, acknowledgment health) carries
// neither, and no screen links to one.
func linkable(def *ast.Definition, view []string) bool {
	if def == nil {
		return false
	}
	for _, field := range def.Fields {
		if field.Name == recordIDField || slices.Contains(view, field.Name) {
			return true
		}
	}

	return false
}

// RenderReferenceFragments writes one fragment per kind type selecting its
// reference view: scalars as they are, a kind it links to through that
// kind's own fragment, and a plain object such as a state by its scalars.
func RenderReferenceFragments(schema *ast.Schema, registry *permission.Registry) (string, error) {
	names, kinds, err := referenceTypes(schema, registry)
	if err != nil {
		return "", err
	}
	referenced := make(map[string]struct{}, len(names))
	for _, name := range names {
		referenced[name] = struct{}{}
	}

	var b strings.Builder
	b.WriteString("# Generated by go run ./internal/api/graphql/gqlext/refgen from the reference\n")
	b.WriteString("# views in the permission registry. Do not edit. A linking screen spreads\n")
	b.WriteString("# ...<Type>Reference to show a record it links to; see\n")
	b.WriteString("# docs/engineering/reference-views.md.\n")
	for _, name := range names {
		def := schema.Types[name]
		resource, _ := registry.Get(kinds[name].String())
		fmt.Fprintf(&b, "\nfragment %s on %s {\n", ReferenceFragmentName(name), name)
		for _, field := range def.Fields {
			if field.Name != recordIDField && !slices.Contains(resource.ReferenceView, field.Name) {
				continue
			}
			child := schema.Types[field.Type.Name()]
			switch {
			case child == nil || child.Kind == ast.Scalar || child.Kind == ast.Enum:
				fmt.Fprintf(&b, "  %s\n", field.Name)
			case isReferenced(referenced, child.Name):
				fmt.Fprintf(
					&b,
					"  %s {\n    ...%s\n  }\n",
					field.Name,
					ReferenceFragmentName(child.Name),
				)
			case kinds[child.Name] != "":
				fmt.Fprintf(&b, "  %s {\n    id\n  }\n", field.Name)
			default:
				leaves := scalarFields(schema, child)
				if len(leaves) == 0 {
					continue
				}
				fmt.Fprintf(&b, "  %s {\n", field.Name)
				for _, leaf := range leaves {
					fmt.Fprintf(&b, "    %s\n", leaf)
				}
				b.WriteString("  }\n")
			}
		}
		b.WriteString("}\n")
	}

	return b.String(), nil
}

func isReferenced(referenced map[string]struct{}, name string) bool {
	_, ok := referenced[name]
	return ok
}

func scalarFields(schema *ast.Schema, def *ast.Definition) []string {
	out := make([]string, 0, len(def.Fields))
	for _, field := range def.Fields {
		if len(field.Arguments) > 0 || strings.HasPrefix(field.Name, "__") {
			continue
		}
		child := schema.Types[field.Type.Name()]
		if child == nil || child.Kind == ast.Scalar || child.Kind == ast.Enum {
			out = append(out, field.Name)
		}
	}
	return out
}

// RenderReferenceViews writes the client's copy of every kind's reference
// view and of which GraphQL type shows which kind, so a screen can tell a
// field withheld for want of a kind's read from one that is empty. A kind
// only REST responses carry, such as a document, is listed by its view.
func RenderReferenceViews(schema *ast.Schema, registry *permission.Registry) (string, error) {
	kinds, err := KindTypes(schema, registry)
	if err != nil {
		return "", err
	}
	resources := make([]string, 0, len(kinds))
	for _, kind := range kinds {
		if !slices.Contains(resources, kind.String()) {
			resources = append(resources, kind.String())
		}
	}
	for _, def := range registry.All() {
		if len(def.ReferenceView) > 0 && !slices.Contains(resources, def.Resource) {
			resources = append(resources, def.Resource)
		}
	}
	slices.Sort(resources)
	types := make([]string, 0, len(kinds))
	for name := range kinds {
		types = append(types, name)
	}
	slices.Sort(types)

	var b strings.Builder
	b.WriteString(
		"// Generated by go run ./internal/api/graphql/gqlext/refgen from the reference views in\n",
	)
	b.WriteString("// the permission registry. Do not edit.\n\n")
	b.WriteString("export const REFERENCE_VIEWS = {\n")
	for _, resource := range resources {
		fields := registry.ReferenceView(resource)
		quoted := make([]string, 0, len(fields))
		for _, field := range fields {
			quoted = append(quoted, fmt.Sprintf("%q", field))
		}
		line := fmt.Sprintf("  %s: [%s],", resource, strings.Join(quoted, ", "))
		if len(line) <= clientPrintWidth {
			b.WriteString(line + "\n")
			continue
		}
		fmt.Fprintf(&b, "  %s: [\n", resource)
		for _, field := range quoted {
			fmt.Fprintf(&b, "    %s,\n", field)
		}
		b.WriteString("  ],\n")
	}
	b.WriteString("} as const satisfies Record<string, readonly string[]>;\n\n")
	b.WriteString("export type ReferenceKind = keyof typeof REFERENCE_VIEWS;\n\n")
	b.WriteString("export const KIND_OF_TYPE: Readonly<Record<string, ReferenceKind>> = {\n")
	for _, name := range types {
		fmt.Fprintf(&b, "  %s: %q,\n", name, kinds[name].String())
	}
	b.WriteString("};\n")

	return b.String(), nil
}
