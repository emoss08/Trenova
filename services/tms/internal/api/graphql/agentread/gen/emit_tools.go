const (
	toolsFile  = "graphqlreads_gen.go"
	kindObject = "object"
)

// field is one GraphQL field or input field, described as the tool's
// parameters are derived from it.
type field struct {
	Name        string
	Type        string
	Kind        string
	List        bool
	NonNull     bool
	Selected    bool
	Enum        []string
	Description string
	// Fields are a selected record's own fields, one level down, so a
	// filter on profile.endorsement can be typed by WorkerProfile's field.
	Fields []field
}

// variable is one of an operation's variables. An unpaged list takes each
// as a parameter, described by the root field argument it is sent as.
type variable struct {
	Name        string
	Type        string
	NonNull     bool
	List        bool
	Kind        string
	Enum        []string
	Description string
}

// besideRead is an operation a list reads alongside its own.
type besideRead struct {
	Operation string
	RootField string
	Resource  string
	Input     string
}

type toolRead struct {
	Tool        string
	Verb        string
	Operation   string
	Reason      string
	RootField   string
	Node        string
	Resource    string
	EntityAlias string
	EntityType  string
	Unpaged     bool
	Variables   []variable
	Fields      []field
	Alongside   []besideRead
}

type toolsData struct {
	Imports []importLine
	Reads   []toolRead
	Inputs  map[string][]field
	Names   []string
}

