package main

import (
	"bytes"
	"fmt"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"text/template"

	"github.com/vektah/gqlparser/v2/ast"
)

const toolsFile = "graphqlreads_gen.go"

// field is one GraphQL field or input field, described as the tool's
// parameters are derived from it.
type field struct {
	Name        string
	Type        string
	Kind        string
	List        bool
	NonNull     bool
	Selected    bool
	Enum        []string
	Description string
}

type variable struct {
	Name    string
	Type    string
	NonNull bool
	List    bool
}

type toolRead struct {
	Tool        string
	Verb        string
	Operation   string
	Reason      string
	RootField   string
	Node        string
	Resource    string
	EntityAlias string
	EntityType  string
	Variables   []variable
	Fields      []field
}

type toolsData struct {
	Imports []importLine
	Reads   []toolRead
	Inputs  map[string][]field
	Names   []string
}

var toolsTemplate = template.Must(template.New("tools").Funcs(template.FuncMap{
	"quote": strconv.Quote,
}).Parse(`// Code generated by agentread/gen. DO NOT EDIT.

package agentquerytoolservice

import (
	"github.com/emoss08/trenova/pkg/domaintypes"
{{- range .Imports }}
	{{ .Alias }} "{{ .Path }}"
{{- end }}
)

// graphQLReads are the tools that read through a persisted GraphQL
// operation, and what each one's parameters are derived from.
var graphQLReads = map[string]graphQLRead{
{{- range .Reads }}
	{{ quote .Tool }}: {
		Verb:      {{ quote .Verb }},
		Operation: {{ quote .Operation }},
{{- if .Reason }}
		Reason:    {{ quote .Reason }},
{{- end }}
		RootField: {{ quote .RootField }},
		Node:      {{ quote .Node }},
		Resource:  {{ quote .Resource }},
		Entity: func() domaintypes.PostgresSearchable { return new({{ .EntityAlias }}.{{ .EntityType }}) },
		Variables: []graphQLVariable{
{{- range .Variables }}
			{Name: {{ quote .Name }}, Type: {{ quote .Type }}, NonNull: {{ .NonNull }}, List: {{ .List }}},
{{- end }}
		},
		Fields: []graphQLField{
{{- range .Fields }}
			{{ template "field" . }}
{{- end }}
		},
	},
{{- end }}
}

// graphQLInputs are the input types the bound operations' variables take,
// with every input they hold.
var graphQLInputs = map[string][]graphQLField{
{{- range $name := .Names }}
	{{ quote $name }}: {
{{- range index $.Inputs $name }}
		{{ template "field" . }}
{{- end }}
	},
{{- end }}
}
{{ define "field" -}}
{Name: {{ quote .Name }}, Type: {{ quote .Type }}, Kind: {{ quote .Kind }}, List: {{ .List }}, NonNull: {{ .NonNull }}
{{- if .Selected }}, Selected: true{{ end }}
{{- if .Enum }}, Enum: []string{ {{- range $i, $v := .Enum }}{{ if $i }}, {{ end }}{{ quote $v }}{{ end -}} }{{ end }}
{{- if .Description }}, Description: {{ quote .Description }}{{ end }}},
{{- end }}
`))

func writeTools(
	dir string,
	schema *ast.Schema,
	bindings []*binding,
	types map[string]goType,
) error {
	data := &toolsData{Inputs: make(map[string][]field)}
	aliases := make(map[string]string)
	for _, b := range bindings {
		gt := types[b.Node]
		alias := aliasFor(aliases, gt.Path)
		data.Reads = append(data.Reads, toolRead{
			Tool:        b.Tool,
			Verb:        b.Verb,
			Operation:   b.Operation.Name,
			Reason:      b.Reason,
			RootField:   b.RootField.Name,
			Node:        b.Node,
			Resource:    string(b.Resource),
			EntityAlias: alias,
			EntityType:  gt.Name,
			Variables:   variables(b.Operation.Query),
			Fields:      nodeFields(schema, b),
		})
		for _, v := range b.Operation.Query.Operations[0].VariableDefinitions {
			collectInputs(schema, v.Type.Name(), data.Inputs)
		}
	}
	for p, alias := range aliases {
		data.Imports = append(data.Imports, importLine{Alias: alias, Path: p})
	}
	sort.Slice(
		data.Imports,
		func(i, j int) bool { return data.Imports[i].Path < data.Imports[j].Path },
	)
	data.Names = sortedKeys(data.Inputs)

	var buf bytes.Buffer
	if err := toolsTemplate.Execute(&buf, data); err != nil {
		return fmt.Errorf("render tool bindings: %w", err)
	}

	return writeGo(filepath.Join(dir, toolsFile), buf.Bytes())
}

func aliasFor(aliases map[string]string, importPath string) string {
	if alias, ok := aliases[importPath]; ok {
		return alias
	}
	base := path.Base(importPath)
	alias := base
	taken := func(a string) bool {
		for _, existing := range aliases {
			if existing == a {
				return true
			}
		}
		return false
	}
	for i := 2; taken(alias); i++ {
		alias = base + strconv.Itoa(i)
	}
	aliases[importPath] = alias

	return alias
}

func variables(doc *ast.QueryDocument) []variable {
	op := doc.Operations[0]
	out := make([]variable, 0, len(op.VariableDefinitions))
	for _, v := range op.VariableDefinitions {
		out = append(out, variable{
			Name:    v.Variable,
			Type:    v.Type.Name(),
			NonNull: v.Type.NonNull,
			List:    v.Type.Elem != nil,
		})
	}

	return out
}

// nodeFields are every field of the record type the tool reads, in schema
// order, each marked with whether the operation selects it: a filter is
// offered on any field the server lets a table filter on, and a result
// carries only what the operation selects.
func nodeFields(schema *ast.Schema, b *binding) []field {
	selected := selectedFields(b)
	def := schema.Types[b.Node]
	out := make([]field, 0, len(def.Fields))
	for _, definition := range def.Fields {
		if strings.HasPrefix(definition.Name, "__") {
			continue
		}
		f := describeField(schema, definition.Name, definition.Type, definition.Description)
		_, f.Selected = selected[definition.Name]
		out = append(out, f)
	}

	return out
}

// selectedFields are the fields the operation selects on each record it
// reads: the connection's node for a list, the result for a get.
func selectedFields(b *binding) map[string]struct{} {
	doc := b.Operation.Query
	fragments := make(map[string]*ast.FragmentDefinition, len(doc.Fragments))
	for _, fragment := range doc.Fragments {
		fragments[fragment.Name] = fragment
	}
	out := make(map[string]struct{})
	var root *ast.Field
	for _, selection := range doc.Operations[0].SelectionSet {
		if f, ok := selection.(*ast.Field); ok && f.Name == b.RootField.Name {
			root = f
		}
	}
	if root == nil {
		return out
	}
	set := root.SelectionSet
	if b.Verb == verbList {
		set = childSet(collect(set, fragments), edgesField)
		set = childSet(collect(set, fragments), nodeField)
	}
	for _, f := range collect(set, fragments) {
		out[f.Name] = struct{}{}
	}

	return out
}

func collect(set ast.SelectionSet, fragments map[string]*ast.FragmentDefinition) []*ast.Field {
	var out []*ast.Field
	for _, selection := range set {
		switch s := selection.(type) {
		case *ast.Field:
			out = append(out, s)
		case *ast.InlineFragment:
			out = append(out, collect(s.SelectionSet, fragments)...)
		case *ast.FragmentSpread:
			if fragment, ok := fragments[s.Name]; ok {
				out = append(out, collect(fragment.SelectionSet, fragments)...)
			}
		}
	}

	return out
}

func childSet(fields []*ast.Field, name string) ast.SelectionSet {
	var out ast.SelectionSet
	for _, f := range fields {
		if f.Name == name {
			out = append(out, f.SelectionSet...)
		}
	}

	return out
}

func describeField(schema *ast.Schema, name string, typ *ast.Type, description string) field {
	named := typ.Name()
	f := field{
		Name:        name,
		Type:        named,
		List:        typ.Elem != nil,
		NonNull:     typ.NonNull,
		Description: strings.TrimSpace(description),
	}
	def := schema.Types[named]
	switch {
	case def == nil:
		f.Kind = "scalar"
	case def.Kind == ast.Enum:
		f.Kind = "enum"
		for _, value := range def.EnumValues {
			f.Enum = append(f.Enum, value.Name)
		}
	case def.Kind == ast.InputObject:
		f.Kind = "input"
	case def.Kind == ast.Scalar:
		f.Kind = "scalar"
	default:
		f.Kind = "object"
	}

	return f
}

func collectInputs(schema *ast.Schema, name string, out map[string][]field) {
	if _, done := out[name]; done {
		return
	}
	def := schema.Types[name]
	if def == nil || def.Kind != ast.InputObject {
		return
	}
	fields := make([]field, 0, len(def.Fields))
	out[name] = fields
	for _, f := range def.Fields {
		fields = append(fields, describeField(schema, f.Name, f.Type, f.Description))
	}
	out[name] = fields
	for _, f := range def.Fields {
		collectInputs(schema, f.Type.Name(), out)
	}
}
