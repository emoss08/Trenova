package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/imports"
)

const (
	servicesFile = "services.go"
	servicesType = "Services"
	depsType     = "Deps"
)

type depField struct {
	Name    string
	Type    string
	imports map[string]string
}

type services struct {
	fields []depField
	index  map[string]int
}

func loadServices(resolverDir string) (*services, error) {
	path := filepath.Join(resolverDir, servicesFile)
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}

	aliases := map[string]string{}
	for _, imp := range file.Imports {
		p, _ := strconv.Unquote(imp.Path.Value)
		name := filepath.Base(p)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		aliases[name] = p
	}

	st := findStruct(file, servicesType)
	if st == nil {
		return nil, fmt.Errorf("%s declares no struct %s", path, servicesType)
	}

	s := &services{index: map[string]int{}}
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			continue
		}
		var buf bytes.Buffer
		if err = printer.Fprint(&buf, fset, f.Type); err != nil {
			return nil, err
		}
		used := map[string]string{}
		ast.Inspect(f.Type, func(n ast.Node) bool {
			sel, isSel := n.(*ast.SelectorExpr)
			if !isSel {
				return true
			}
			id, isIdent := sel.X.(*ast.Ident)
			if !isIdent {
				return true
			}
			if p, known := aliases[id.Name]; known {
				used[id.Name] = p
			}
			return true
		})
		for _, name := range f.Names {
			s.index[name.Name] = len(s.fields)
			s.fields = append(
				s.fields,
				depField{Name: name.Name, Type: buf.String(), imports: used},
			)
		}
	}
	return s, nil
}

func findStruct(file *ast.File, name string) *ast.StructType {
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gd.Specs {
			ts, isType := spec.(*ast.TypeSpec)
			if !isType || ts.Name.Name != name {
				continue
			}
			if st, isStruct := ts.Type.(*ast.StructType); isStruct {
				return st
			}
		}
	}
	return nil
}

func (s *services) usedBy(dir string) ([]depField, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", dir, err)
	}

	used := map[int]struct{}{}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || name == resolverTypesFile ||
			strings.HasPrefix(name, ".") {
			continue
		}
		file, parseErr := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if parseErr != nil {
			return nil, fmt.Errorf("parse %s: %w", name, parseErr)
		}
		ast.Inspect(file, func(n ast.Node) bool {
			var id *ast.Ident
			switch n := n.(type) {
			case *ast.SelectorExpr:
				id = n.Sel
			case *ast.KeyValueExpr:
				id, _ = n.Key.(*ast.Ident)
			}
			if id != nil {
				if i, ok := s.index[id.Name]; ok {
					used[i] = struct{}{}
				}
			}
			return true
		})
	}

	idx := make([]int, 0, len(used))
	for i := range used {
		idx = append(idx, i)
	}
	sort.Ints(idx)
	fields := make([]depField, 0, len(idx))
	for _, i := range idx {
		fields = append(fields, s.fields[i])
	}
	return fields, nil
}

func writeDomainTypes(d *resolverDomain) error {
	imps := map[string]string{"base": d.BaseImport}
	for _, f := range d.DepsFields {
		for alias, p := range f.imports {
			imps[alias] = p
		}
	}
	aliases := make([]string, 0, len(imps))
	for alias := range imps {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)

	var b strings.Builder
	b.WriteString("// Code generated by github.com/99designs/gqlgen, DO NOT EDIT.\n\n")
	b.WriteString("package " + d.Package + "\n\nimport (\n")
	for _, alias := range aliases {
		fmt.Fprintf(&b, "\t%s %q\n", alias, imps[alias])
	}
	b.WriteString(")\n\ntype " + depsType + " struct {\n\t*base.Core\n")
	for _, f := range d.DepsFields {
		fmt.Fprintf(&b, "\t%s %s\n", f.Name, f.Type)
	}
	b.WriteString("}\n")
	for _, t := range d.Types {
		fmt.Fprintf(&b, "\ntype %s struct{ *%s }\n", t.Name, depsType)
	}

	path := filepath.Join(d.Dir, resolverTypesFile)
	src, err := imports.Process(path, []byte(b.String()), &imports.Options{
		Comments:   true,
		TabIndent:  true,
		TabWidth:   8,
		FormatOnly: true,
	})
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	return writeFile(path, src)
}
