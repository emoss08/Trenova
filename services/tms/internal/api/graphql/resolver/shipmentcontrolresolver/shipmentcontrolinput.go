package shipmentcontrolresolver

import (
	"github.com/emoss08/trenova/internal/api/graphql/gqlmodel"
	"github.com/emoss08/trenova/internal/api/graphql/resolver/gqlinput"
	"github.com/emoss08/trenova/internal/modules/identity/domain/shipmentcontrol"
)

func shipmentControlFromInput(
	existing *shipmentcontrol.ShipmentControl,
	input *gqlmodel.UpdateShipmentControlInput,
) (*shipmentcontrol.ShipmentControl, error) {
	parse := gqlinput.NewParser()
	entity := &shipmentcontrol.ShipmentControl{
		ID:             existing.ID,
		BusinessUnitID: existing.BusinessUnitID,
		OrganizationID: existing.OrganizationID,
		Version:        int64(input.Version),
		CreatedAt:      existing.CreatedAt,
		UpdatedAt:      existing.UpdatedAt,
		BusinessUnit:   existing.BusinessUnit,
		Organization:   existing.Organization,
		MaxShipmentWeightLimit: parse.Int32(
			"maxShipmentWeightLimit",
			input.MaxShipmentWeightLimit,
		),
		AutoDelayShipments: input.AutoDelayShipments,
		AutoDelayShipmentsThreshold: parse.Int16Ptr(
			"autoDelayShipmentsThreshold",
			input.AutoDelayShipmentsThreshold,
		),
		DetentionThreshold: parse.Int16Ptr(
			"detentionThreshold",
			input.DetentionThreshold,
		),
		AutoCancelShipmentsThreshold: parse.Int16Ptr(
			"autoCancelShipmentsThreshold",
			input.AutoCancelShipmentsThreshold,
		),
		AutoCancelShipments:          input.AutoCancelShipments,
		TrackDetentionTime:           input.TrackDetentionTime,
		AutoGenerateDetentionCharges: input.AutoGenerateDetentionCharges,
		DetentionChargeID:            parse.IDPtr("detentionChargeId", input.DetentionChargeID),
		UseDetentionPolicyEngine:     input.UseDetentionPolicyEngine,
		DefaultDetentionPolicyID: parse.IDPtr(
			"defaultDetentionPolicyId",
			input.DefaultDetentionPolicyID,
		),
		TrackCustomerRejections: input.TrackCustomerRejections,
		CheckForDuplicateBOLs:   input.CheckForDuplicateBols,
		AllowMoveRemovals:       input.AllowMoveRemovals,
		CheckHazmatSegregation:  input.CheckHazmatSegregation,
	}
	if err := parse.Err(); err != nil {
		return nil, err
	}

	return entity, nil
}
