func TestShipmentControlResolvers_CheckTheShipmentControlPermission(t *testing.T) {
	t.Parallel()

	calls := []struct {
		name      string
		operation permission.Operation
		run       func(ctx context.Context, deps *Deps) error
	}{
		{"shipmentControl", permission.OpRead, func(ctx context.Context, deps *Deps) error {
			_, err := (&QueryResolver{deps}).ShipmentControl(ctx)
			return err
		}},
		{"updateShipmentControl", permission.OpUpdate, func(ctx context.Context, deps *Deps) error {
			_, err := (&MutationResolver{deps}).UpdateShipmentControl(
				ctx,
				gqlmodel.UpdateShipmentControlInput{},
			)
			return err
		}},
	}

	for _, call := range calls {
		t.Run(call.name, func(t *testing.T) {
			t.Parallel()

			engine := resolvertest.RefusingEngine()
			deps := &Deps{Core: &resolvercore.Core{PermissionEngine: engine}}
			ctx := resolvertest.AuthedContext(t, resolvertest.UserAuthContext())

			err := call.run(ctx, deps)

			resolvertest.RequireRefused(
				t,
				err,
				engine,
				permission.ResourceShipmentControl,
				call.operation,
			)
		})
	}
}

func TestShipmentControlFromInput_MapsEveryFieldOntoTheStoredControl(t *testing.T) {
	t.Parallel()

	existing := &shipmentcontrol.ShipmentControl{
		ID:             pulid.MustNew("x_"),
		BusinessUnitID: pulid.MustNew("bu_"),
		OrganizationID: pulid.MustNew("org_"),
		Version:        3,
		CreatedAt:      100,
		UpdatedAt:      200,
	}
	v2 := 5
	v3 := 6
	v4 := 7
	v8 := pulid.MustNew("x_")
	v8Raw := v8.String()
	v10 := pulid.MustNew("x_")
	v10Raw := v10.String()

	entity, err := shipmentControlFromInput(existing, &gqlmodel.UpdateShipmentControlInput{
		Version:                      3,
		MaxShipmentWeightLimit:       3,
		AutoDelayShipments:           true,
		AutoDelayShipmentsThreshold:  &v2,
		DetentionThreshold:           &v3,
		AutoCancelShipmentsThreshold: &v4,
		AutoCancelShipments:          true,
		TrackDetentionTime:           true,
		AutoGenerateDetentionCharges: true,
		DetentionChargeID:            &v8Raw,
		UseDetentionPolicyEngine:     true,
		DefaultDetentionPolicyID:     &v10Raw,
		TrackCustomerRejections:      true,
		CheckForDuplicateBols:        true,
		AllowMoveRemovals:            true,
		CheckHazmatSegregation:       true,
	})
	require.NoError(t, err)

	assert.Equal(t, existing.ID, entity.ID)
	assert.Equal(t, existing.BusinessUnitID, entity.BusinessUnitID)
	assert.Equal(t, existing.OrganizationID, entity.OrganizationID)
	assert.Equal(t, int64(100), entity.CreatedAt)
	assert.Equal(t, int64(3), entity.Version)
	assert.Equal(t, int32(3), entity.MaxShipmentWeightLimit)
	assert.True(t, entity.AutoDelayShipments)
	require.NotNil(t, entity.AutoDelayShipmentsThreshold)
	assert.Equal(t, int16(5), *entity.AutoDelayShipmentsThreshold)
	require.NotNil(t, entity.DetentionThreshold)
	assert.Equal(t, int16(6), *entity.DetentionThreshold)
	require.NotNil(t, entity.AutoCancelShipmentsThreshold)
	assert.Equal(t, int16(7), *entity.AutoCancelShipmentsThreshold)
	assert.True(t, entity.AutoCancelShipments)
	assert.True(t, entity.TrackDetentionTime)
	assert.True(t, entity.AutoGenerateDetentionCharges)
	require.NotNil(t, entity.DetentionChargeID)
	assert.Equal(t, v8, *entity.DetentionChargeID)
	assert.True(t, entity.UseDetentionPolicyEngine)
	require.NotNil(t, entity.DefaultDetentionPolicyID)
	assert.Equal(t, v10, *entity.DefaultDetentionPolicyID)
	assert.True(t, entity.TrackCustomerRejections)
	assert.True(t, entity.CheckForDuplicateBOLs)
	assert.True(t, entity.AllowMoveRemovals)
	assert.True(t, entity.CheckHazmatSegregation)
}

func TestShipmentControlFromInput_NamesAMalformedField(t *testing.T) {
	t.Parallel()

	raw := "not-an-id"
	_, err := shipmentControlFromInput(
		&shipmentcontrol.ShipmentControl{},
		&gqlmodel.UpdateShipmentControlInput{
			DetentionChargeID: &raw,
		},
	)

	var multiErr *errortypes.MultiError
	require.ErrorAs(t, err, &multiErr)
	require.NotEmpty(t, multiErr.Errors)
	assert.Equal(t, "detentionChargeId", multiErr.Errors[0].Field)
}
