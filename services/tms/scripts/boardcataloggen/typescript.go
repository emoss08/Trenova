package main

import (
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/emoss08/trenova/internal/modules/agent/domain/boardregistry"
	"github.com/emoss08/trenova/internal/modules/workspace/domain/boardcatalog"
)

const typeScriptHeader = `// Code generated by services/tms/scripts/boardcataloggen. DO NOT EDIT.
//
// Source of truth: services/tms/internal/modules/agent/domain/boardregistry
// Regenerate with: cd services/tms && go run ./scripts/boardcataloggen
// scripts/boardcataloggen/typescript_test.go fails when this file drifts from the catalog.

`

type measureEntry struct {
	key     string
	measure string
	value   boardcatalog.ValueKind
	bar     bool
}

func measureEntries() []measureEntry {
	measures := boardregistry.Catalog().Measures()
	entries := make([]measureEntry, 0, len(measures)*4)
	for idx := range measures {
		measure := &measures[idx]
		names := append([]string{measure.Name}, measure.Aliases...)
		for _, name := range names {
			key := string(measure.Kind) + ":" + strings.ToLower(name)
			if slices.ContainsFunc(
				entries,
				func(entry measureEntry) bool { return entry.key == key },
			) {
				continue
			}
			entries = append(
				entries,
				measureEntry{
					key:     key,
					measure: measure.Name,
					value:   measure.Value,
					bar:     measure.Shape.Bar(),
				},
			)
		}
	}
	slices.SortFunc(entries, func(a, b measureEntry) int { return strings.Compare(a.key, b.key) })

	return entries
}

func metricNames() [][2]string {
	metrics := boardregistry.Catalog().Metrics()
	names := make([][2]string, 0, len(metrics)*3)
	for idx := range metrics {
		metric := &metrics[idx]
		for _, name := range append([]string{metric.Name}, metric.Aliases...) {
			key := strings.ToLower(name)
			if slices.ContainsFunc(names, func(pair [2]string) bool { return pair[0] == key }) {
				continue
			}
			names = append(names, [2]string{key, metric.Name})
		}
	}
	slices.SortFunc(names, func(a, b [2]string) int { return strings.Compare(a[0], b[0]) })

	return names
}

const printWidth = 100

var plainKey = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsKey(key string) string {
	if plainKey.MatchString(key) {
		return key
	}

	return strconv.Quote(key)
}

func writeEntry(sb *strings.Builder, key string, fields [][2]string) {
	parts := make([]string, 0, len(fields))
	for _, field := range fields {
		parts = append(parts, field[0]+": "+field[1])
	}
	line := "  " + tsKey(key) + ": { " + strings.Join(parts, ", ") + " },"
	if len(line) <= printWidth {
		sb.WriteString(line + "\n")
		return
	}
	sb.WriteString("  " + tsKey(key) + ": {\n")
	for _, part := range parts {
		sb.WriteString("    " + part + ",\n")
	}
	sb.WriteString("  },\n")
}

func typeScript() string {
	var sb strings.Builder
	sb.WriteString(typeScriptHeader)
	sb.WriteString(
		"/** A record's measure: its own name, the kind of value it reads, and whether it draws a bar. */\n",
	)
	sb.WriteString(
		"export type BoardMeasure = { measure: string; value: string; bar: boolean };\n\n",
	)
	sb.WriteString(
		"/** What a metric block reserves before it is read: its form, and the rows it lists. */\n",
	)
	sb.WriteString(
		"export type BoardMetricSketch = { form: string; rows?: number };\n\n",
	)
	sb.WriteString(
		"/** A record's measure by `kind:name`, the name lowercased and any alias the tools take. */\n",
	)
	sb.WriteString("export const BOARD_MEASURES: Record<string, BoardMeasure> = {\n")
	for _, entry := range measureEntries() {
		writeEntry(&sb, entry.key, [][2]string{
			{"measure", strconv.Quote(entry.measure)},
			{"value", strconv.Quote(string(entry.value))},
			{"bar", strconv.FormatBool(entry.bar)},
		})
	}
	sb.WriteString("};\n\n")
	sb.WriteString("/** The measure a kind's rows take when an answer names none, by kind. */\n")
	sb.WriteString("export const BOARD_DEFAULT_MEASURES: Record<string, string> = {\n")
	for _, kind := range boardregistry.Catalog().Kinds() {
		if measure, ok := boardregistry.Catalog().DefaultMeasure(kind.Kind); ok {
			sb.WriteString(
				"  " + tsKey(string(kind.Kind)) + ": " + strconv.Quote(measure.Name) + ",\n",
			)
		}
	}
	sb.WriteString("};\n\n")
	sb.WriteString("/** A metric's own name by its name or any alias, lowercased. */\n")
	sb.WriteString("export const BOARD_METRIC_NAMES: Record<string, string> = {\n")
	for _, pair := range metricNames() {
		sb.WriteString("  " + tsKey(pair[0]) + ": " + strconv.Quote(pair[1]) + ",\n")
	}
	sb.WriteString("};\n\n")
	sb.WriteString("/** Each metric's sketch, by its own name. */\n")
	sb.WriteString("export const BOARD_METRIC_SKETCH: Record<string, BoardMetricSketch> = {\n")
	metrics := boardregistry.Catalog().Metrics()
	slices.SortFunc(
		metrics,
		func(a, b boardcatalog.Metric) int { return strings.Compare(a.Name, b.Name) },
	)
	for idx := range metrics {
		metric := &metrics[idx]
		fields := [][2]string{{"form", strconv.Quote(string(metric.Form))}}
		if metric.Sketch.Rows > 0 {
			fields = append(fields, [2]string{"rows", strconv.Itoa(metric.Sketch.Rows)})
		}
		writeEntry(&sb, metric.Name, fields)
	}
	sb.WriteString("};\n")

	return sb.String()
}
