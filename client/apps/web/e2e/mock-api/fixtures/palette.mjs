function buildHos(worker, anchor) {
  const [drive, shift, cycle] = worker.hos;
  return {
    workerId: worker.id,
    workerName: `${worker.first} ${worker.last}`,
    provider: "Samsara",
    providerDriverId: `sam_${worker.externalId}`,
    dutyStatus: worker.available ? "offDuty" : "driving",
    driveRemainingMs: drive,
    shiftRemainingMs: shift,
    cycleRemainingMs: cycle,
    cycleTomorrowMs: cycle,
    breakRemainingMs: H(8),
    cycleStartedAt: anchor - 4 * 86400,
    shiftDrivingViolationMs: 0,
    cycleViolationMs: 0,
    currentVehicleId: null,
    currentTractorId: null,
    rulesetCycle: "USA70hour8day",
    rulesetShift: "US Interstate Property",
    rulesetJurisdiction: "US",
    driveLimitMs: H(11),
    shiftLimitMs: H(14),
    cycleLimitMs: H(70),
    breakLimitMs: H(8),
    recordedAt: anchor - 2 * MINUTE,
  };
}

export function createPaletteState(anchor) {
  const shipments = SHIPMENTS.map((raw, index) => buildShipment(raw, index, anchor));
  return {
    shipments,
    events: new Map(shipments.map((s) => [s.id, buildEvents(s, anchor)])),
    documents: DOCS.map((raw) => buildDocument(raw, anchor)),
    hos: new Map(PALETTE_WORKERS.map((w) => [w.id, buildHos(w, anchor)])),
    favorites: PALETTE_PAGE_FAVORITES.map(([id, pageUrl, pageTitle]) => ({
      id,
      organizationId: "org_mock",
      businessUnitId: "bu_mock",
      userId: "usr_mock",
      pageUrl,
      pageTitle,
      version: 1,
      createdAt: anchor - 86400,
      updatedAt: anchor - 86400,
    })),
    asks: new Map(),
  };
}
