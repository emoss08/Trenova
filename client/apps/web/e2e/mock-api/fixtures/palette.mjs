function buildEvents(shipment, anchor) {
  return shipment.palette.events.map(([summary, minutesAgo], index) => ({
    __typename: "ShipmentLifecycleEvent",
    id: `evt_${shipment.id}_${index}`,
    organizationId: "org_mock",
    businessUnitId: "bu_mock",
    shipmentId: shipment.id,
    type: "StatusChanged",
    severity: "info",
    actorType: "system",
    actorId: null,
    actorLabel: "Trenova",
    summary,
    metadata: {},
    occurredAt: anchor - minutesAgo * MINUTE,
    correlationId: null,
    actor: null,
    shipment: { id: shipment.id, proNumber: shipment.proNumber },
    proNumber: shipment.proNumber,
    previousStatus: null,
    newStatus: null,
    reason: null,
  }));
}

