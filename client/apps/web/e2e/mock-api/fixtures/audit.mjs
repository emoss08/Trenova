    action: spec.action ?? `${spec.resource}.${spec.operation}`,
    resourceId: spec.resourceId,
    entityRef: spec.entityRef ?? null,
    correlationId: spec.correlationId ?? `req_${spec.id.slice(3)}`,
    comment: spec.comment,
    ipAddress: spec.ipAddress ?? (person ? "203.0.113.24" : null),
    userAgent: person ? "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_5) Chrome/131.0" : null,
    traceId: spec.traceId ?? "4bf92f3577b34da6a3ce929d0e0e4736",
    apiKeyId: spec.apiKeyId ?? null,
    category: spec.category ?? "User",
    retentionClass: spec.retentionClass ?? "Operational",
    channel: spec.channel ?? "web",
