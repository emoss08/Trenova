export function entryTypeLabel(type: string, t: TranslateFn): string {
  switch (type) {
    case "Standard":
      return t("Standard");
    case "Adjusting":
      return t("Adjusting");
    case "Closing":
      return t("Closing");
    case "Reversal":
      return t("Reversal");
    case "Reclassification":
      return t("Reclassification");
    case "AutoGenerated":
      return t("Automatic");
    case "Reconciliation":
      return t("Reconciliation");
    case "Opening":
      return t("Opening");
    default:
      return type;
  }
}

export function entryStanding(entry: JournalCardEntry, t: TranslateFn): Standing {
  switch (entry.status) {
    case "Draft":
      return { label: t("Draft"), tone: "draft", mark: "dot" };
    case "Pending":
      return { label: t("Waiting on approval"), tone: "progress", mark: "dot" };
    case "Approved":
      return entry.isPosted
        ? { label: t("Posted"), tone: "success", mark: "check" }
        : { label: t("Approved, not posted"), tone: "progress", mark: "dot" };
    case "Posted":
      return { label: t("Posted"), tone: "success", mark: "check" };
    case "Reversed":
      return { label: t("Reversed"), tone: "muted", mark: "dot" };
    case "Rejected":
      return { label: t("Rejected"), tone: "danger", mark: "x" };
    case "Void":
      return { label: t("Voided"), tone: "muted", mark: "dot" };
    default:
      return { label: entry.status, tone: "muted", mark: "dot" };
  }
}

/** An entry that left the way to the ledger: taken back, refused or voided. */
export function entryIsOff(entry: JournalCardEntry): boolean {
  return entry.status === "Reversed" || entry.status === "Rejected" || entry.status === "Void";
}

export function entryKicker(card: DeskJournalEntryCard, t: TranslateFn): string[] {
  const { entry } = card;
  return [
    entry.entryNumber,
    entryTypeLabel(entry.entryType, t),
    entry.isAutoGenerated ? t("Recorded by Trenova") : t("Recorded by hand"),
  ];
}

export function entryTitle(entry: JournalCardEntry, t: TranslateFn): string {
  return entry.description.trim() || t("Journal entry {0}", entry.entryNumber);
}

export function entrySubtitle(card: DeskJournalEntryCard, t: TranslateFn): string {
  const parts: string[] = [];
  const party = card.lines.find((line) => line.customerName)?.customerName;
  if (party) parts.push(party);
  parts.push(t("{0, plural, one {# line} other {# lines}}", card.lines.length));
  return parts.join(" · ");
}

/** The entry's figure: what each side comes to, struck through once it is taken back. */
export function entryFigure(
  entry: JournalCardEntry,
  t: TranslateFn,
): { struck: boolean; caption: string } {
  if (entry.status === "Reversed" || entry.status === "Void") {
    return {
      struck: true,
      caption: entry.status === "Reversed" ? t("each side · reversed") : t("each side · void"),
    };
  }
  return {
    struck: false,
    caption:
      entry.totalDebit === entry.totalCredit
        ? t("each side · balanced")
        : t("debits and credits differ"),
  };
}

/** The entry's way to the general ledger: booked, approved where the organization reviews it, posted. */
export function entryTrack(entry: JournalCardEntry, t: TranslateFn): CardTrackStep[] {
  const reachedApproval = entry.isApproved || entry.isPosted || entry.approvedAt !== null;
  const steps: CardTrackStep[] = [];
  const booked: CardTrackStep["state"] = entry.status === "Draft" ? "now" : "done";
  steps.push({ key: "booked", label: t("Recorded"), state: booked });
  if (entry.requiresApproval) {
    steps.push({
      key: "approved",
      label: t("Approved"),
      state: entry.status === "Pending" ? "now" : reachedApproval ? "done" : "next",
    });
  }
  const posted: CardTrackStep["state"] =
    entry.isPosted && !entryIsOff(entry)
      ? "now"
      : entry.isPosted
        ? "done"
        : entry.status === "Approved"
          ? "now"
          : "next";
  steps.push({ key: "posted", label: t("Posted"), state: posted });
  return steps;
}

export function entryTrackNote(card: DeskJournalEntryCard, t: TranslateFn): string {
  const { entry } = card;
  const batch = card.source?.batchNumber;
  switch (entry.status) {
    case "Draft":
      return t("Recorded {0} · not yet sent for approval", cardDay(entry.createdAt));
    case "Pending":
      return t(
        "Your organization reviews journals before they reach the general ledger · waiting since {0}",
        cardDay(entry.createdAt),
      );
    case "Approved":
      if (!entry.isPosted) {
        return card.approvedBy
          ? t(
              "Approved {0} by {1} · waiting to be posted",
              cardMoment(entry.approvedAt),
              card.approvedBy.name,
            )
          : t("Approved {0} · waiting to be posted", cardMoment(entry.approvedAt));
      }
      break;
    case "Reversed":
      return card.reversedBy
        ? t(
            "Taken back {0} by {1}, so nothing it booked remains",
            accountingDay(entry.reversalDate),
            card.reversedBy.entryNumber,
          )
        : t("Taken back {0}, so nothing it booked remains", accountingDay(entry.reversalDate));
    case "Rejected":
      return card.rejectedBy
        ? t("Rejected by {0}; it never reached the general ledger", card.rejectedBy.name)
        : t("Rejected; it never reached the general ledger");
    case "Void":
      return t("Voided; nothing it booked stands");
    default:
      break;
  }
  if (entry.postedAt === null) return "";
  const posted = cardMoment(entry.postedAt);
  return batch ? t("Posted {0} · batch {1}", posted, batch) : t("Posted {0}", posted);
}

/** Who booked, approved and posted the entry, under its track. */
export function entrySignoffs(card: DeskJournalEntryCard, t: TranslateFn): Signoff[] {
  const { entry } = card;
  const notYet = t("Not yet");
  const rows: Signoff[] = [
    {
      key: "booked",
      step: t("Recorded"),
      who: card.createdBy?.name ?? (entry.isAutoGenerated ? t("Trenova") : "—"),
      when: cardMoment(entry.createdAt),
    },
  ];
  if (entry.requiresApproval) {
    rows.push({
      key: "approved",
      step: t("Approved"),
      who: card.approvedBy?.name ?? "—",
      when: entry.approvedAt ? cardMoment(entry.approvedAt) : notYet,
    });
  }
  rows.push({
    key: "posted",
    step: t("Posted"),
    who: card.postedBy?.name ?? (entry.isPosted && entry.isAutoGenerated ? t("Trenova") : "—"),
    when: entry.postedAt ? cardMoment(entry.postedAt) : notYet,
  });
  return rows;
}

/** A source of journal entries as the card links it: its mark, what it is, and whether it has a card. */
export type SourceRef = {
  entity: RecordEntityType | null;
  mark: string;
  kind: string;
  number: string;
  id: string;
};

export function sourceRef(source: JournalCardSource, t: TranslateFn): SourceRef {
  const base = {
    number: source.sourceDocumentNumber || source.sourceObjectId,
    id: source.sourceObjectId,
  };
  switch (source.sourceObjectType) {
    case "Invoice":
      return { ...base, entity: "invoice", mark: t("INV"), kind: t("Invoice") };
    case "InvoiceAdjustment":
      return { ...base, entity: null, mark: t("ADJ"), kind: t("Invoice adjustment") };
    case "CustomerPayment":
      return { ...base, entity: null, mark: t("PMT"), kind: t("Customer payment") };
    case "DriverSettlement":
      return { ...base, entity: "driver_settlement", mark: t("PAY"), kind: t("Worker settlement") };
    case "CarrierSettlement":
      return {
        ...base,
        entity: "carrier_settlement",
        mark: t("AP"),
        kind: t("Carrier settlement"),
      };
    case "ManualJournalRequest":
      return { ...base, entity: "manual_journal", mark: t("MJ"), kind: t("Manual journal") };
    case "JournalEntry":
      return { ...base, entity: "journal_entry", mark: t("JE"), kind: t("Journal entry") };
    case "FiscalYear":
      return { ...base, entity: null, mark: t("FY"), kind: t("Fiscal year close") };
    default:
      return { ...base, entity: null, mark: "—", kind: source.sourceObjectType };
  }
}

/** One side of a reversed pair: the entry, which way it moves the books, and whether it is this one. */
export type PairRow = { entry: JournalCardEntry; mine: boolean; sign: 1 | -1 };

/**
 * A reversed entry beside the entry that reversed it, the original first:
 * the two bracketed together come to nothing. Null when this entry is neither.
 */
export function reversalPair(card: DeskJournalEntryCard): PairRow[] | null {
  const { entry } = card;
  if (card.reversedBy) {
    return [
      { entry, mine: true, sign: 1 },
      { entry: card.reversedBy, mine: false, sign: -1 },
    ];
  }
  if (entry.isReversal && card.reversalOf) {
    return [
      { entry: card.reversalOf, mine: false, sign: 1 },
      { entry, mine: true, sign: -1 },
    ];
  }
  return null;
}

/** Why the entry was reversed, kept as written: the request's code and words, or the entry's own note. */
export function reversalWhy(card: DeskJournalEntryCard): { code: string; text: string } | null {
  const reversal = card.reversal;
  if (reversal && (reversal.status === "Posted" || card.reversedBy || card.entry.isReversal)) {
    return { code: reversal.reasonCode, text: reversal.reasonText };
  }
  const text = card.entry.reversalReason.trim();
  return text ? { code: "", text } : null;
}

/** A reversal request that stands against the entry but has not posted yet. */
export function standingReversal(card: DeskJournalEntryCard): JournalCardReversal | null {
  const reversal = card.reversal;
  if (!reversal || card.entry.isReversal || card.reversedBy) return null;
  return reversal.status === "Requested" ||
    reversal.status === "PendingApproval" ||
    reversal.status === "Approved"
    ? reversal
    : null;
}

/** What became of a reversal request, as one sentence naming who asked and when. */
export function reversalSlipTitle(
  reversal: JournalCardReversal,
  by: string | null,
  t: TranslateFn,
): string {
  const day = cardDay(reversal.createdAt);
  switch (reversal.status) {
    case "Approved":
      return by
        ? t("{0} asked for a reversal on {1}; it is approved and waits to post", by, day)
        : t("A reversal asked for on {0} is approved and waits to post", day);
    case "Rejected":
      return by
        ? t("{0} asked for a reversal on {1}; it was rejected", by, day)
        : t("A reversal asked for on {0} was rejected", day);
    case "Cancelled":
      return by
        ? t("{0} asked for a reversal on {1}; it was cancelled", by, day)
        : t("A reversal asked for on {0} was cancelled", day);
    default:
      return by
        ? t("{0} asked for a reversal on {1}; it waits on approval", by, day)
        : t("A reversal asked for on {0} waits on approval", day);
  }
}

/** The last reversal request, when it was refused or withdrawn and nothing else stands. */
export function refusedReversal(card: DeskJournalEntryCard): JournalCardReversal | null {
  const reversal = card.reversal;
  if (!reversal || card.entry.isReversal || card.reversedBy) return null;
  return reversal.status === "Rejected" || reversal.status === "Cancelled" ? reversal : null;
}

/** The steps a person can take on the entry now, before checking their permissions. */
export type EntryActions = { approve: boolean; post: boolean; reverse: boolean };

export function entryActions(card: DeskJournalEntryCard): EntryActions {
  const { entry } = card;
  return {
    approve: entry.status === "Pending" && !entry.isApproved,
    post: entry.status === "Approved" && !entry.isPosted,
    reverse:
      entry.isPosted &&
      entry.status === "Posted" &&
      !entry.isReversal &&
      card.reversedBy === null &&
      standingReversal(card) === null,
  };
}

/** Why the entry cannot post as things stand, or null when it can. */
export function postingBlocker(posting: JournalCardPosting | null): string | null {
  return posting && posting.refusal ? posting.refusal : null;
}

/** The bar's hint while the entry waits: where it will post, or why it cannot. */
export function waitingHint(card: DeskJournalEntryCard, t: TranslateFn): string | null {
  const { posting } = card;
  if (!posting) return null;
  if (posting.refusal) return posting.refusal;
  if (!posting.period) return null;
  return card.entry.status === "Pending"
    ? t("Approving lets it post to {0}", posting.period.name)
    : t("It posts to {0} on {1}", posting.period.name, accountingDay(posting.accountingDate));
}
