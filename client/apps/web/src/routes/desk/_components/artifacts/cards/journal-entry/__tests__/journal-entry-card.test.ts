function withCard(card: DeskJournalEntryCard, change: (copy: DeskJournalEntryCard) => void) {
  const copy = structuredClone(card);
  change(copy);
  return copy;
}

function request(status: string, extra: Partial<JournalCardReversal> = {}): JournalCardReversal {
  return {
    id: "jrev_91",
    status,
    reasonCode: "WRONG_ACCOUNT",
    reasonText: "Booked to freight revenue; it was fuel surcharge.",
    requestedAccountingDate: 1792108800,
    rejectionReason: null,
    cancelReason: null,
    createdAt: 1792081200,
    approvedAt: null,
    postedAt: null,
    ...extra,
  } as JournalCardReversal;
}

describe("entryStanding", () => {
  it("reads each status as its pill, an approved entry already posted as posted", () => {
    const standing = (status: string, isPosted = false) =>
      entryStanding({ ...posted.entry, status, isPosted }, t);

    expect(standing("Draft")).toEqual({ label: "Draft", tone: "draft", mark: "dot" });
    expect(standing("Pending")).toEqual({
      label: "Waiting on approval",
      tone: "progress",
      mark: "dot",
    });
    expect(standing("Approved")).toEqual({
      label: "Approved, not posted",
      tone: "progress",
      mark: "dot",
    });
    expect(standing("Approved", true)).toEqual({ label: "Posted", tone: "success", mark: "check" });
    expect(standing("Posted", true)).toEqual({ label: "Posted", tone: "success", mark: "check" });
    expect(standing("Reversed", true)).toEqual({ label: "Reversed", tone: "muted", mark: "dot" });
    expect(standing("Rejected")).toEqual({ label: "Rejected", tone: "danger", mark: "x" });
    expect(standing("Void")).toEqual({ label: "Voided", tone: "muted", mark: "dot" });
    expect(standing("Archived")).toEqual({ label: "Archived", tone: "muted", mark: "dot" });
  });

  it("reads reversed, rejected and void entries as off the way to the ledger", () => {
    expect(
      ["Draft", "Pending", "Approved", "Posted", "Reversed", "Rejected", "Void"].map((status) =>
        entryIsOff({ ...posted.entry, status }),
      ),
    ).toEqual([false, false, false, false, true, true, true]);
  });
});

describe("the entry's head", () => {
  it("names the entry, its type and who booked it", () => {
    expect(entryKicker(posted, t)).toEqual(["JE-2610-00418", "Standard", "Recorded by Trenova"]);
    expect(entryKicker(writeoff, t)).toEqual(["JE-2610-00422", "Standard", "Recorded by hand"]);
    expect(entryTypeLabel("AutoGenerated", t)).toBe("Automatic");
    expect(entryTypeLabel("Reclassification", t)).toBe("Reclassification");
  });

  it("titles the entry by its description, or by its number when it has none", () => {
    expect(entryTitle(posted.entry, t)).toBe("Invoice INV-2610-0042 posted");
    expect(entryTitle({ ...posted.entry, description: "  " }, t)).toBe(
      "Journal entry JE-2610-00418",
    );
  });

  it("names the first customer a line books to and counts the lines", () => {
    expect(entrySubtitle(posted, t)).toBe("Acme Foods · 4 lines");
    expect(entrySubtitle(pending, t)).toBe("4 lines");
    expect(
      entrySubtitle(
        withCard(pending, (copy) => copy.lines.splice(1)),
        t,
      ),
    ).toBe("1 line");
  });

  it("strikes the figure of a reversed or void entry and says when the sides differ", () => {
    expect(entryFigure(posted.entry, t)).toEqual({
      struck: false,
      caption: "each side · balanced",
    });
    expect(entryFigure(reversed.entry, t)).toEqual({
      struck: true,
      caption: "each side · reversed",
    });
    expect(entryFigure({ ...posted.entry, status: "Void" }, t)).toEqual({
      struck: true,
      caption: "each side · void",
    });
    expect(entryFigure({ ...posted.entry, totalCredit: 361200 }, t)).toEqual({
      struck: false,
      caption: "debits and credits differ",
    });
  });
});

describe("entryTrack", () => {
  const states = (card: DeskJournalEntryCard) =>
    entryTrack(card.entry, t).map((step) => `${step.label}:${step.state}`);

  it("skips approval where the entry needs none and stands on posted once it is", () => {
    expect(states(posted)).toEqual(["Recorded:done", "Posted:now"]);
  });

  it("waits on approval for an entry the organization reviews", () => {
    expect(states(pending)).toEqual(["Recorded:done", "Approved:now", "Posted:next"]);
  });

  it("waits to post once approved, and stands on booked while a draft", () => {
    const approved = withCard(pending, (copy) => {
      copy.entry.status = "Approved";
      copy.entry.isApproved = true;
      copy.entry.approvedAt = 1792143000;
    });
    expect(states(approved)).toEqual(["Recorded:done", "Approved:done", "Posted:now"]);
    const draft = withCard(pending, (copy) => {
      copy.entry.status = "Draft";
    });
    expect(states(draft)).toEqual(["Recorded:now", "Approved:next", "Posted:next"]);
  });

  it("marks every step a reversed entry reached as done", () => {
    expect(states(reversed)).toEqual(["Recorded:done", "Posted:done"]);
    expect(states(reversal)).toEqual(["Recorded:done", "Approved:done", "Posted:now"]);
  });
});

describe("entryTrackNote", () => {
  it("says when and in which batch an entry posted", () => {
    expect(entryTrackNote(posted, t)).toBe(
      `Posted ${cardMoment(posted.entry.postedAt)} · batch JB-2610-0031`,
    );
    expect(
      entryTrackNote(
        withCard(posted, (copy) => (copy.source = null)),
        t,
      ),
    ).toBe(`Posted ${cardMoment(posted.entry.postedAt)}`);
  });

  it("says an entry waiting on approval is waiting, and since when", () => {
    expect(entryTrackNote(pending, t)).toBe(
      `Your organization reviews journals before they reach the general ledger · waiting since ${cardDay(pending.entry.createdAt)}`,
    );
  });

  it("names who approved an entry waiting to post", () => {
    const approved = withCard(pending, (copy) => {
      copy.entry.status = "Approved";
      copy.entry.approvedAt = 1792143000;
      copy.approvedBy = { id: "usr_priya", name: "Priya Shah" };
    });
    expect(entryTrackNote(approved, t)).toBe(
      `Approved ${cardMoment(1792143000)} by Priya Shah · waiting to be posted`,
    );
  });

  it("names the entry that took a reversed one back, on its booking day", () => {
    expect(entryTrackNote(reversed, t)).toBe(
      "Taken back Oct 16, 2026 by JE-2610-00427, so nothing it booked remains",
    );
  });

  it("names who rejected an entry, and says a void one stands for nothing", () => {
    const rejected = withCard(pending, (copy) => {
      copy.entry.status = "Rejected";
      copy.rejectedBy = { id: "usr_priya", name: "Priya Shah" };
    });
    expect(entryTrackNote(rejected, t)).toBe(
      "Rejected by Priya Shah; it never reached the general ledger",
    );
    expect(
      entryTrackNote(
        withCard(posted, (copy) => (copy.entry.status = "Void")),
        t,
      ),
    ).toBe("Voided; nothing it booked stands");
  });
});

