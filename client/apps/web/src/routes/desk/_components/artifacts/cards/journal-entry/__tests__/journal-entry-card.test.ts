describe("reversals", () => {
  it("brackets a reversed entry with the entry that took it back, the original first", () => {
    expect(
      reversalPair(reversed)?.map((row) => [row.entry.entryNumber, row.mine, row.sign]),
    ).toEqual([
      ["JE-2610-00402", true, 1],
      ["JE-2610-00427", false, -1],
    ]);
    expect(
      reversalPair(reversal)?.map((row) => [row.entry.entryNumber, row.mine, row.sign]),
    ).toEqual([
      ["JE-2610-00402", false, 1],
      ["JE-2610-00427", true, -1],
    ]);
    expect(reversalPair(posted)).toBeNull();
  });

  it("gives the request's code and words for a reversed pair", () => {
    const why = { code: "DUPLICATE", text: "Billed twice; voided and rebilled as INV-2610-0051." };
    expect(reversalWhy(reversed)).toEqual(why);
    expect(reversalWhy(reversal)).toEqual(why);
  });

  it("falls back to the entry's own reversal note, and to nothing", () => {
    const noted = withCard(reversed, (copy) => {
      copy.reversal = null;
      copy.entry.reversalReason = " Rebilled. ";
    });
    expect(reversalWhy(noted)).toEqual({ code: "", text: "Rebilled." });
    expect(reversalWhy(posted)).toBeNull();
  });

  it("keeps a waiting request's words out of the why until it posts", () => {
    const asked = withCard(posted, (copy) => (copy.reversal = request("Requested")));
    expect(reversalWhy(asked)).toBeNull();
  });

  it("holds up a request that stands, and sets aside one refused or withdrawn", () => {
    for (const status of ["Requested", "PendingApproval", "Approved"]) {
      const asked = withCard(posted, (copy) => (copy.reversal = request(status)));
      expect(standingReversal(asked)?.status).toBe(status);
      expect(refusedReversal(asked)).toBeNull();
    }
    for (const status of ["Rejected", "Cancelled"]) {
      const refused = withCard(posted, (copy) => (copy.reversal = request(status)));
      expect(standingReversal(refused)).toBeNull();
      expect(refusedReversal(refused)?.status).toBe(status);
    }
    expect(standingReversal(reversed)).toBeNull();
    expect(refusedReversal(reversal)).toBeNull();
  });

  it("says what became of a request in one sentence, with and without who asked", () => {
    const day = cardDay(1792081200);
    expect(reversalSlipTitle(request("Requested"), "Dana Ruiz", t)).toBe(
      `Dana Ruiz asked for a reversal on ${day}; it waits on approval`,
    );
    expect(reversalSlipTitle(request("Approved"), "Dana Ruiz", t)).toBe(
      `Dana Ruiz asked for a reversal on ${day}; it is approved and waits to post`,
    );
    expect(reversalSlipTitle(request("Rejected"), null, t)).toBe(
      `A reversal asked for on ${day} was rejected`,
    );
    expect(reversalSlipTitle(request("Cancelled"), null, t)).toBe(
      `A reversal asked for on ${day} was cancelled`,
    );
  });
});

describe("entryActions", () => {
  it("offers approval to an entry waiting on it and posting to one approved", () => {
    expect(entryActions(pending)).toEqual({ approve: true, post: false, reverse: false });
    const approved = withCard(pending, (copy) => {
      copy.entry.status = "Approved";
      copy.entry.isApproved = true;
    });
    expect(entryActions(approved)).toEqual({ approve: false, post: true, reverse: false });
  });

  it("offers a reversal of a posted entry only while nothing has reversed it or asks to", () => {
    expect(entryActions(posted)).toEqual({ approve: false, post: false, reverse: true });
    expect(entryActions(reversed).reverse).toBe(false);
    expect(entryActions(reversal).reverse).toBe(false);
    expect(
      entryActions(withCard(posted, (copy) => (copy.reversal = request("PendingApproval"))))
        .reverse,
    ).toBe(false);
    expect(
      entryActions(withCard(posted, (copy) => (copy.reversal = request("Rejected")))).reverse,
    ).toBe(true);
  });
});

describe("posting", () => {
  it("blocks posting with the server's refusal, and not otherwise", () => {
    expect(postingBlocker(pending.posting)).toBeNull();
    expect(postingBlocker(null)).toBeNull();
    expect(
      postingBlocker({ period: null, accountingDate: null, refusal: "September 2026 is closed" }),
    ).toBe("September 2026 is closed");
  });

  it("says where approving lets an entry post, and where an approved one posts", () => {
    expect(waitingHint(pending, t)).toBe("Approving lets it post to October 2026");
    const approved = withCard(pending, (copy) => (copy.entry.status = "Approved"));
    expect(waitingHint(approved, t)).toBe("It posts to October 2026 on Oct 13, 2026");
  });

  it("gives the refusal in place of where it posts, and nothing for a posted entry", () => {
    const refused = withCard(pending, (copy) => {
      copy.posting = { period: null, accountingDate: null, refusal: "September 2026 is closed" };
    });
    expect(waitingHint(refused, t)).toBe("September 2026 is closed");
    expect(waitingHint(posted, t)).toBeNull();
  });
});
