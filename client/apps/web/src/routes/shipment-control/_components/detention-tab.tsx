import {
  AccessorialChargeAutocompleteField,
  DetentionPolicyAutocompleteField,
} from "@/components/autocomplete-fields";
import { NumberField } from "@/components/fields/number-field";
import { SwitchField } from "@/components/fields/switch-field";
import { SettingsReveal } from "@/components/settings/settings-reveal";
import {
  SettingsNested,
  SettingsSection,
  SettingsSections,
} from "@/components/settings/settings-section";
import type { ShipmentControl } from "@/types/shipment-control";
import { useT } from "@trenova/shared/i18n/use-t";
import { useFormContext, useWatch } from "react-hook-form";

/**
 * How detention is worked out and charged: by detention policies, or, while they are off, by
 * one flat free-time allowance and a single charge.
 */
export function DetentionTab() {
  const t = useT();
  const { control } = useFormContext<ShipmentControl>();
  const usePolicies = useWatch({ control, name: "useDetentionPolicyEngine" });
  const trackDetention = useWatch({ control, name: "trackDetentionTime" });
  const flatClock = !usePolicies && trackDetention;

  return (
    <SettingsSections>
      <SettingsSection
        title={t("Detention policies")}
        description={t(
          "Policies set the clock, free time, tiered rates and notices for each customer or location, and show how every charge was worked out.",
        )}
      >
        <SwitchField
          control={control}
          name="useDetentionPolicyEngine"
          label={t("Use detention policies")}
          description={t("Works out detention from your policies instead of one flat allowance.")}
        />
        <SettingsNested show={usePolicies}>
          <DetentionPolicyAutocompleteField
            control={control}
            name="defaultDetentionPolicyId"
            defaultEligibleOnly
            label={t("Default policy")}
            description={t(
              "The policy a stop falls back to when no other policy covers it. It must be active, cover all freight, already be in effect and have no end date.",
            )}
            placeholder={t("Select a policy")}
            required={usePolicies}
          />
        </SettingsNested>
      </SettingsSection>

      <SettingsReveal show={!usePolicies}>
        <SettingsSection
          title={t("Flat detention")}
          description={t(
            "One free-time allowance for every stop, and one charge billed for the time past it.",
          )}
        >
          <SwitchField
            control={control}
            name="trackDetentionTime"
            label={t("Track detention time")}
            description={t(
              "Records how long a driver waits at each pickup and delivery past the free time.",
            )}
          />
          <SettingsNested show={flatClock}>
            <NumberField
              control={control}
              name="detentionThreshold"
              label={t("Free time")}
              description={t("How long a driver may wait at a stop before detention starts.")}
              placeholder="120"
              sideText={t("minutes")}
              min={1}
              max={32767}
              required={flatClock}
            />
            <AccessorialChargeAutocompleteField
              control={control}
              name="detentionChargeId"
              label={t("Detention charge")}
              description={t("The accessorial charge detention is billed as.")}
              placeholder={t("Select a charge")}
              required={flatClock}
            />
            <SwitchField
              control={control}
              name="autoGenerateDetentionCharges"
              label={t("Add detention charges automatically")}
              description={t(
                "Adds the detention charge to a shipment once a stop runs past its free time.",
              )}
            />
          </SettingsNested>
        </SettingsSection>
      </SettingsReveal>
    </SettingsSections>
  );
}
