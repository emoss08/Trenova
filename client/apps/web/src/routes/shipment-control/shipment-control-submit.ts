import type { ShipmentControl } from "@/types/shipment-control";

/**
 * The record as it is saved: a setting the page hides because another one makes it
 * meaningless is sent the way the server requires it then, so a save is never refused for a
 * field the person cannot see. Detention policies replace the flat detention clock, so while
 * they are on the clock is off; and charges are generated only from a clock that runs.
 */
export function sanitizeShipmentControlForSubmit(values: ShipmentControl): ShipmentControl {
  const next = { ...values };

  if (next.useDetentionPolicyEngine) {
    next.trackDetentionTime = false;
  }

  if (!next.trackDetentionTime) {
    next.autoGenerateDetentionCharges = false;
  }

  return next;
}
