import type { SettingsTabSpec } from "@/components/settings/settings-tab";
import { PlanFeature } from "@/lib/plan-feature";
import type { ShipmentControl } from "@/types/shipment-control";
import { usePlanFeature } from "@trenova/shared/hooks/use-plan-feature";
import { defineLabels } from "@trenova/shared/i18n/labels";

export type ShipmentControlTab = "entry" | "automation" | "detention";

export type ShipmentControlField = keyof ShipmentControl & string;

export type ShipmentControlTabSpec = SettingsTabSpec<ShipmentControlField> & {
  value: ShipmentControlTab;
};

const TAB_LABELS = defineLabels({
  entry: "Shipment entry",
  automation: "Status automation",
  detention: "Detention",
});

/** The form fields each tab holds, so a refused save marks and opens the tab at fault. */
const TAB_FIELDS: Record<ShipmentControlTab, readonly ShipmentControlField[]> = {
  entry: [
    "maxShipmentWeightLimit",
    "checkForDuplicateBols",
    "checkHazmatSegregation",
    "allowMoveRemovals",
  ],
  automation: [
    "autoDelayShipments",
    "autoDelayShipmentsThreshold",
    "autoCancelShipments",
    "autoCancelShipmentsThreshold",
  ],
  detention: [
    "useDetentionPolicyEngine",
    "defaultDetentionPolicyId",
    "trackDetentionTime",
    "detentionThreshold",
    "autoGenerateDetentionCharges",
    "detentionChargeId",
  ],
};

const TAB_ORDER: readonly ShipmentControlTab[] = ["entry", "automation", "detention"];

/**
 * The tabs an organization sees, in order. Detention is offered only when the plan includes
 * it: without it no detention is computed or charged, whatever these settings say. The form
 * and its loading state both read this, so the outline has the form's tabs.
 */
export function shipmentControlTabs({
  detention,
}: {
  detention: boolean;
}): ShipmentControlTabSpec[] {
  return TAB_ORDER.filter((tab) => tab !== "detention" || detention).map((tab) => ({
    value: tab,
    label: TAB_LABELS[tab],
    fields: TAB_FIELDS[tab],
  }));
}

/** The tabs this organization sees, for the form and its loading state alike. */
export function useShipmentControlTabs(): ShipmentControlTabSpec[] {
  const detention = usePlanFeature(PlanFeature.Detention).available;

  return shipmentControlTabs({ detention });
}
