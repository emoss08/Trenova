import { describe, expect, it } from "vitest";
import { sanitizeShipmentControlForSubmit } from "../shipment-control-submit";
import { savedShipmentControl } from "./shipment-control-fixture";

const flatClock = {
  ...savedShipmentControl,
  trackDetentionTime: true,
  autoGenerateDetentionCharges: true,
  detentionChargeId: "acc_01",
  detentionThreshold: 120,
};

describe("sanitizeShipmentControlForSubmit", () => {
  it("sends a running flat clock as it is", () => {
    expect(sanitizeShipmentControlForSubmit(flatClock)).toEqual(flatClock);
  });

  it("turns the flat clock and its generated charges off while detention policies are on", () => {
    expect(
      sanitizeShipmentControlForSubmit({
        ...flatClock,
        useDetentionPolicyEngine: true,
        defaultDetentionPolicyId: "dp_01",
      }),
    ).toEqual({
      ...flatClock,
      useDetentionPolicyEngine: true,
      defaultDetentionPolicyId: "dp_01",
      trackDetentionTime: false,
      autoGenerateDetentionCharges: false,
    });
  });

  it("generates no charges from a clock that is off, and keeps the charge and free time", () => {
    expect(sanitizeShipmentControlForSubmit({ ...flatClock, trackDetentionTime: false })).toEqual({
      ...flatClock,
      trackDetentionTime: false,
      autoGenerateDetentionCharges: false,
    });
  });

  it("leaves the record it was given untouched", () => {
    const values = { ...flatClock, useDetentionPolicyEngine: true };
    sanitizeShipmentControlForSubmit(values);

    expect(values.trackDetentionTime).toBe(true);
  });
});
