import { TestRouter } from "@trenova/shared/testing/test-router";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { cleanup, render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { domMax, LazyMotion, MotionGlobalConfig } from "motion/react";
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from "vitest";
import type { ShipmentControl } from "@/types/shipment-control";
import ShipmentControlForm from "../_components/shipment-control-form";
import { savedShipmentControl } from "./shipment-control-fixture";
import { resetPlan, withoutDetention } from "./shipment-control-plan";

const served = vi.hoisted(() => ({
  control: null as unknown,
  refusal: null as unknown,
  sent: [] as unknown[],
}));

vi.mock("@/lib/queries/shipment-control", () => ({
  shipmentControl: {
    get: Object.assign(
      () => ({ queryKey: ["shipment-control"], queryFn: async () => served.control }),
      { _def: ["shipment-control"] },
    ),
  },
}));

// The pickers read their options from the server; a plain field registered under the same
// name stands in, so a server error still lands where the picker would show it.
vi.mock("@/components/autocomplete-fields", async () => {
  const { useController } = await import("react-hook-form");
  function PickerStandIn({
    control,
    name,
    label,
    defaultEligibleOnly,
  }: {
    control: never;
    name: string;
    label: string;
    defaultEligibleOnly?: boolean;
  }) {
    const { field, fieldState } = useController({ control, name });
    return (
      <div
        data-slot="setting-row"
        role="group"
        aria-label={label}
        data-default-eligible-only={defaultEligibleOnly ? "" : undefined}
      >
        <input
          aria-label={label}
          value={(field.value as string | null) ?? ""}
          onChange={(event) => field.onChange(event.target.value || null)}
        />
        {fieldState.error ? <span>{fieldState.error.message}</span> : null}
      </div>
    );
  }
  return {
    AccessorialChargeAutocompleteField: PickerStandIn,
    DetentionPolicyAutocompleteField: PickerStandIn,
  };
});

// The save hands the refusal the server returned to the form, as the real mutation does.
vi.mock("@/hooks/use-optimistic-mutation", () => ({
  useOptimisticMutation: ({ form }: { form: unknown }) => ({
    mutateAsync: async (values: unknown) => {
      served.sent.push(values);
      if (!served.refusal) return;
      const { handleMutationError } = await vi.importActual<
        typeof import("@/hooks/use-api-mutation")
      >("@/hooks/use-api-mutation");
      handleMutationError({ error: served.refusal, form: form as never });
      throw served.refusal;
    },
  }),
}));

const flatClock: ShipmentControl = {
  ...savedShipmentControl,
  trackDetentionTime: true,
  autoGenerateDetentionCharges: true,
  detentionChargeId: "acc_01",
  detentionThreshold: 120,
};

function renderForm(search = "") {
  const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } });

  return render(
    <TestRouter search={search}>
      <LazyMotion features={domMax}>
        <QueryClientProvider client={queryClient}>
          <ShipmentControlForm />
        </QueryClientProvider>
      </LazyMotion>
    </TestRouter>,
  );
}

beforeAll(() => {
  MotionGlobalConfig.skipAnimations = true;
});
afterAll(() => {
  MotionGlobalConfig.skipAnimations = false;
});

afterEach(() => {
  served.control = savedShipmentControl;
  served.refusal = null;
  served.sent = [];
  cleanup();
  resetPlan();
});

describe("shipment control tabs", () => {
  it("offers entry, automation and detention, in that order", async () => {
    served.control = savedShipmentControl;

    renderForm();
    await screen.findByText("Entry checks");

    expect(screen.getAllByRole("tab").map((tab) => tab.textContent)).toEqual([
      "Shipment entry",
      "Status automation",
      "Detention",
    ]);
  });

  it("leaves detention out when the plan does not include it", async () => {
    served.control = savedShipmentControl;
    withoutDetention();

    renderForm();
    await screen.findByText("Entry checks");

    expect(screen.getAllByRole("tab").map((tab) => tab.textContent)).toEqual([
      "Shipment entry",
      "Status automation",
    ]);
    expect(screen.queryByText("Use detention policies")).toBeNull();
  });
});

describe("shipment control conditional rows", () => {
  it("asks for the delay and cancel limits only once each is turned on", async () => {
    served.control = savedShipmentControl;
    const user = userEvent.setup();

    renderForm("?tab=automation");
    await screen.findByText("Delays");
    expect(screen.queryByText("Late after")).toBeNull();
    expect(screen.queryByText("Cancel after")).toBeNull();

    await user.click(screen.getByRole("switch", { name: /Mark late shipments delayed/ }));
    expect(await screen.findByText("Late after")).toBeInTheDocument();
    expect(screen.queryByText("Cancel after")).toBeNull();

    await user.click(screen.getByRole("switch", { name: /Cancel stale new shipments/ }));
    expect(await screen.findByText("Cancel after")).toBeInTheDocument();
  });

  it("opens the free time, charge and auto-charge rows under a running flat clock", async () => {
    served.control = savedShipmentControl;
    const user = userEvent.setup();

    renderForm("?tab=detention");
    await screen.findByText("Flat detention");
    expect(screen.queryByText("Free time")).toBeNull();

    await user.click(screen.getByRole("switch", { name: /Track detention time/ }));

    expect(await screen.findByText("Free time")).toBeInTheDocument();
    expect(screen.getByRole("group", { name: "Detention charge" })).toBeInTheDocument();
    expect(screen.getByText("Add detention charges automatically")).toBeInTheDocument();
  });

  it("swaps the flat clock for a default policy when detention policies are turned on", async () => {
    served.control = flatClock;
    const user = userEvent.setup();

    renderForm("?tab=detention");
    await screen.findByText("Free time");
    expect(screen.queryByRole("group", { name: "Default policy" })).toBeNull();

    await user.click(screen.getByRole("switch", { name: /Use detention policies/ }));

    expect(await screen.findByRole("group", { name: "Default policy" })).toBeInTheDocument();
    expect(screen.queryByText("Flat detention")).toBeNull();
    expect(screen.queryByText("Free time")).toBeNull();
  });

  it("refuses to turn detention policies on without a default policy", async () => {
    served.control = savedShipmentControl;
    const user = userEvent.setup();

    renderForm("?tab=detention");
    await user.click(await screen.findByRole("switch", { name: /Use detention policies/ }));
    await user.click(await screen.findByRole("button", { name: "Save changes" }));

    const picker = await screen.findByRole("group", { name: "Default policy" });
    expect(
      await within(picker).findByText(
        "Select a default detention policy to use detention policies",
      ),
    ).toBeInTheDocument();
    expect(served.sent).toEqual([]);
  });

  it("offers only the policies that can be the default", async () => {
    served.control = flatClock;
    const user = userEvent.setup();

    renderForm("?tab=detention");
    await user.click(await screen.findByRole("switch", { name: /Use detention policies/ }));

    expect(await screen.findByRole("group", { name: "Default policy" })).toHaveAttribute(
      "data-default-eligible-only",
    );
  });

  it("sends the flat clock off once detention policies replace it", async () => {
    served.control = flatClock;
    const user = userEvent.setup();

    renderForm("?tab=detention");
    await user.click(await screen.findByRole("switch", { name: /Use detention policies/ }));
    await user.type(await screen.findByRole("textbox", { name: "Default policy" }), "dp_01");
    await user.click(await screen.findByRole("button", { name: "Save changes" }));

    await vi.waitFor(() => expect(served.sent).toHaveLength(1));
    expect(served.sent[0]).toEqual({
      ...flatClock,
      useDetentionPolicyEngine: true,
      defaultDetentionPolicyId: "dp_01",
      trackDetentionTime: false,
      autoGenerateDetentionCharges: false,
    });
  });
});

describe("a refused save", () => {
  it("opens and marks Detention when the server refuses the detention charge", async () => {
    served.control = flatClock;
    const { ApiRequestError } = await import("@trenova/shared/lib/api");
    served.refusal = new ApiRequestError(400, {
      type: "https://api.trenova.app/problems/validation-error",
      title: "Validation Failed",
      status: 400,
      detail: "Detention charge does not exist in your organization",
      instance: "/api/v1/shipment-controls/",
      code: "INVALID",
      errors: [
        {
          path: ["detentionChargeId"],
          message: "Detention charge does not exist in your organization",
          code: "INVALID",
          location: "body",
        },
      ],
    } as ConstructorParameters<typeof ApiRequestError>[1]);
    const user = userEvent.setup();

    renderForm();
    await user.click(await screen.findByRole("switch", { name: /Allow removing moves/ }));
    await user.click(await screen.findByRole("button", { name: "Save changes" }));

    const detention = await screen.findByRole("tab", { name: /Detention/, selected: true });
    expect(within(detention).getByText("Has fields to fix")).toBeInTheDocument();
    const charge = screen.getByRole("group", { name: "Detention charge" });
    expect(
      within(charge).getByText("Detention charge does not exist in your organization"),
    ).toBeVisible();
  });
});
