import {
  ShipmentControlDocument,
  UpdateShipmentControlDocument,
  type UpdateShipmentControlInput,
} from "@trenova/graphql/generated/graphql";
import { requestGraphQL } from "@trenova/shared/lib/graphql";
import { safeParse } from "@trenova/shared/lib/parse";
import { shipmentControlSchema, type ShipmentControl } from "@/types/shipment-control";

export function toShipmentControlInput(data: ShipmentControl): UpdateShipmentControlInput {
  return {
    version: data.version ?? 0,
    maxShipmentWeightLimit: data.maxShipmentWeightLimit,
    autoDelayShipments: data.autoDelayShipments,
    autoDelayShipmentsThreshold: data.autoDelayShipmentsThreshold ?? null,
    detentionThreshold: data.detentionThreshold ?? null,
    autoCancelShipmentsThreshold: data.autoCancelShipmentsThreshold ?? null,
    autoCancelShipments: data.autoCancelShipments,
    trackDetentionTime: data.trackDetentionTime,
    autoGenerateDetentionCharges: data.autoGenerateDetentionCharges,
    detentionChargeId: data.detentionChargeId || null,
    useDetentionPolicyEngine: data.useDetentionPolicyEngine,
    defaultDetentionPolicyId: data.defaultDetentionPolicyId || null,
    trackCustomerRejections: data.trackCustomerRejections,
    checkForDuplicateBols: data.checkForDuplicateBols,
    allowMoveRemovals: data.allowMoveRemovals,
    checkHazmatSegregation: data.checkHazmatSegregation,
  };
}

export class ShipmentControlService {
  public async get(options?: { signal?: AbortSignal }) {
    const response = await requestGraphQL({
      document: ShipmentControlDocument,
      operationName: "ShipmentControl",
      signal: options?.signal,
    });

    return safeParse(shipmentControlSchema, response.shipmentControl, "Shipment Control");
  }

  public async update(data: ShipmentControl) {
    const response = await requestGraphQL({
      document: UpdateShipmentControlDocument,
      operationName: "UpdateShipmentControl",
      variables: { input: toShipmentControlInput(data) },
    });

    return safeParse(shipmentControlSchema, response.updateShipmentControl, "Shipment Control");
  }
}
