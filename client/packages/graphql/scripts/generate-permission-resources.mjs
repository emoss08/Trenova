// generate-permission-resources.mjs mirrors the Go permission resource enum into
// TypeScript.
//
// The client checks permissions by resource, so every resource the server can guard has to
// exist here or the check silently cannot be written. The Go side is itself generated, so
// there is a clean source and no reason for this list to be maintained by hand — it had
// drifted by eleven resources before this generator existed.
//
// Only the resource enum is generated. The permissions and routeAccess payload shapes are
// runtime-assembled maps with no Go declaration to read, and are deliberately out of scope.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../../..");

const SOURCE = "services/tms/internal/core/domain/permission/resource_gen.go";
const OUTPUT = "client/packages/shared/src/types/generated/permission-resources.ts";

// Keys are the Go identifier with its Resource prefix removed, verbatim — so Go's
// ResourceAPIKey becomes APIKey, not ApiKey. Applying a casing policy here would mean
// inventing a naming rule the Go source does not have, which is a second thing to drift.
function parseResources(source) {
  const lines = source.split("\n");
  const entries = [];

  for (const line of lines) {
    const grouping = /^\s*\/\/ (.+)$/.exec(line);
    if (grouping) {
      entries.push({ comment: grouping[1].trim() });
      continue;
    }

    const match = /^\s*Resource(\w+)\s+Resource\s*=\s*"([^"]+)"/.exec(line);
    if (match) {
      entries.push({ key: match[1], value: match[2] });
    }
  }

  const resources = entries.filter((entry) => entry.key !== undefined);
  if (resources.length === 0) {
    throw new Error(
      `No Resource constants found in ${SOURCE}. The declaration style changed — update ` +
        `the parser in scripts/generate-permission-resources.mjs rather than hand-editing ` +
        `the generated output.`,
    );
  }

  const byValue = new Map();
  for (const { key, value } of resources) {
    if (byValue.has(value)) {
      throw new Error(
        `Duplicate resource value "${value}" in ${SOURCE} (Resource${byValue.get(value)} and ` +
          `Resource${key}).`,
      );
    }
    byValue.set(value, key);
  }

  return entries;
}

function render(entries) {
  const body = entries
    .map((entry) =>
      entry.comment === undefined
        ? `  ${entry.key}: "${entry.value}",`
        : `\n  // ${entry.comment}`,
    )
    .join("\n")
    .replace(/^\n/, "");

  return `// Code generated by client/packages/graphql/scripts/generate-permission-resources.mjs. DO NOT EDIT.
//
// Source of truth: ${SOURCE}
//
// Regenerate with: pnpm --filter @trenova/graphql codegen
// Drift between these values and the Go source fails the codegen:check CI gate.

export const Resource = {
${body}
} as const;

export type ResourceType = (typeof Resource)[keyof typeof Resource];
`;
}

const source = await readFile(resolve(repoRoot, SOURCE), "utf8");
const entries = parseResources(source);
const outputPath = resolve(repoRoot, OUTPUT);

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, render(entries), "utf8");

process.stdout.write(
  `permission resources: ${entries.filter((e) => e.key !== undefined).length} -> ` +
    `${relative(repoRoot, outputPath)}\n`,
);
