// The client preset writes every document into graphql.ts, one module, and a module is never
// split between chunks: the first page any user opened carried all of the app's documents,
// because the shell needs a few of them. This moves the documents into one module per
// operations file (src/generated/documents/<area>/<file>.ts) and has graphql.ts re-export
// them, so every import keeps working and the bundler places each file's documents with the
// routes that use them. Run after strip-fragment-text.mjs, which leaves every document a
// one-line constant.

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { Kind, parse } from "graphql";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const operationsDir = join(packageRoot, "src/operations");
const generatedDir = join(packageRoot, "src/generated");
const documentsDir = join(generatedDir, "documents");

const DOCUMENT_CONST =
  /^export const ([A-Za-z_][A-Za-z0-9_]*) = (\{"__meta__":.*\}) as unknown as TypedDocumentString<([^<>]*)>;$\n?/gm;
const TYPE_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

// Codegen names a document after its operation in PascalCase (AIAuditEvent becomes
// AiAuditEventDocument), so names are compared by their letters and digits alone.
const nameKey = (name) => name.replace(/[^A-Za-z0-9]/g, "").toLowerCase();

/**
 * definitionFiles maps each operation's and fragment's document, by nameKey, to the
 * operations file that defines it, as a path relative to src/operations without its
 * extension.
 */
export function definitionFiles(sources) {
  const files = new Map();
  for (const [file, source] of sources) {
    for (const definition of parse(source).definitions) {
      if (
        definition.kind !== Kind.OPERATION_DEFINITION &&
        definition.kind !== Kind.FRAGMENT_DEFINITION
      ) {
        continue;
      }
      const name = definition.name?.value;
      if (name === undefined) {
        throw new Error(`split-documents: ${file} has an unnamed operation`);
      }
      const fragment = definition.kind === Kind.FRAGMENT_DEFINITION;
      const key = nameKey(fragment ? `${name}FragmentDoc` : `${name}Document`);
      if (files.has(key)) {
        throw new Error(`split-documents: ${name} is defined in ${files.get(key)} and in ${file}`);
      }
      files.set(key, file);
    }
  }
  return files;
}

/**
 * splitDocuments takes graphql.ts and the definition map, and returns graphql.ts with each
 * document replaced by a re-export, and the module source for every operations file.
 */
export function splitDocuments(graphqlSource, files) {
  const modules = new Map();
  const found = new Set();

  const rest = graphqlSource.replace(DOCUMENT_CONST, (_line, name, value, typeArgs) => {
    const file = files.get(nameKey(name));
    if (file === undefined) {
      throw new Error(`split-documents: no operations file defines ${name}`);
    }
    const types = typeArgs.split(",").map((part) => part.trim());
    for (const type of types) {
      if (!TYPE_NAME.test(type)) {
        throw new Error(`split-documents: ${name} has a type argument it cannot import: ${type}`);
      }
    }
    const module = modules.get(file) ?? { names: [], types: new Set(), body: [] };
    module.names.push(name);
    for (const type of types) if (type !== "unknown") module.types.add(type);
    module.body.push(
      `export const ${name} = ${value} as unknown as TypedDocumentString<${types.join(", ")}>;`,
    );
    modules.set(file, module);
    found.add(nameKey(name));
    return "";
  });

  if (/\bnew TypedDocumentString\(/.test(rest)) {
    throw new Error(
      "split-documents: graphql.ts still builds a document; run strip-fragment-text first",
    );
  }

  const missing = [...files].filter(([key]) => !found.has(key)).map(([, file]) => file);
  if (missing.length > 0) {
    throw new Error(
      `split-documents: graphql.ts has no document for a definition in ${missing.join(", ")}`,
    );
  }

  const sources = new Map();
  const reexports = [];
  for (const file of [...modules.keys()].sort()) {
    const { names, types, body } = modules.get(file);
    const toGraphql = posix.relative(posix.dirname(`documents/${file}`), "graphql");
    const imports = ["TypedDocumentString", ...[...types].sort()].join(", ");
    sources.set(
      `${file}.ts`,
      [
        `// Generated by scripts/split-documents.mjs from src/operations/${file}.graphql. Do not edit.`,
        `import type { ${imports} } from "${toGraphql.startsWith(".") ? toGraphql : `./${toGraphql}`}";`,
        "",
        ...body,
        "",
      ].join("\n"),
    );
    reexports.push(`export { ${names.join(", ")} } from "./documents/${file}";`);
  }

  return { graphql: `${rest.trimEnd()}\n\n${reexports.join("\n")}\n`, modules: sources };
}

async function operationSources(dir) {
  const sources = [];
  for (const entry of await readdir(dir, { withFileTypes: true, recursive: true })) {
    if (!entry.isFile() || !entry.name.endsWith(".graphql")) continue;
    const path = join(entry.parentPath, entry.name);
    const file = relative(operationsDir, path)
      .split(sep)
      .join("/")
      .replace(/\.graphql$/, "");
    sources.push([file, await readFile(path, "utf8")]);
  }
  return sources.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const graphqlPath = join(generatedDir, "graphql.ts");
  const files = definitionFiles(await operationSources(operationsDir));
  const { graphql, modules } = splitDocuments(await readFile(graphqlPath, "utf8"), files);

  await rm(documentsDir, { recursive: true, force: true });
  for (const [file, source] of modules) {
    const path = join(documentsDir, file);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, source);
  }
  await writeFile(graphqlPath, graphql);
}
