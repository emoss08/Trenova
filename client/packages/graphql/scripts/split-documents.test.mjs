import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { definitionFiles, splitDocuments } from "./split-documents.mjs";

const SHIPMENT_OPERATIONS = `fragment ShipmentRowFields on Shipment {
  id
}

query ShipmentTable($input: DataTableConnectionInput!) {
  shipments(input: $input) { edges { node { ...ShipmentRowFields } } }
}

mutation CancelShipment($id: ID!) {
  cancelShipment(id: $id) { id }
}
`;

const CUSTOMER_OPERATIONS = `query CustomerDetail($id: ID!) {
  customer(id: $id) { id }
}
`;

const DOCUMENT_CLASS = `export class TypedDocumentString<TResult, TVariables>
  extends String
  implements DocumentTypeDecoration<TResult, TVariables>
{
  __apiType?: NonNullable<DocumentTypeDecoration<TResult, TVariables>['__apiType']>;
  private value: string;
  public __meta__?: Record<string, any> | undefined;

  constructor(value: string, __meta__?: Record<string, any> | undefined) {
    super(value);
    this.value = value;
    this.__meta__ = __meta__;
  }

  override toString(): string & DocumentTypeDecoration<TResult, TVariables> {
    return this.value;
  }
}
`;

const meta = (value) => JSON.stringify({ __meta__: value });

const GRAPHQL_TS = [
  "export type ShipmentRowFieldsFragment = { id: string };",
  "export type ShipmentTableQuery = { shipments: unknown };",
  "export type ShipmentTableQueryVariables = { input: unknown };",
  DOCUMENT_CLASS,
  `export const ShipmentRowFieldsFragmentDoc = ${meta({ fragmentName: "ShipmentRowFields" })} as unknown as TypedDocumentString<ShipmentRowFieldsFragment, unknown>;`,
  `export const ShipmentTableDocument = ${meta({ kind: "query", name: "ShipmentTable", hash: "sha256:aa" })} as unknown as TypedDocumentString<ShipmentTableQuery, ShipmentTableQueryVariables>;`,
  `export const CancelShipmentDocument = ${meta({ kind: "mutation", name: "CancelShipment", hash: "sha256:bb" })} as unknown as TypedDocumentString<CancelShipmentMutation, CancelShipmentMutationVariables>;`,
  `export const CustomerDetailDocument = ${meta({ kind: "query", name: "CustomerDetail", hash: "sha256:cc" })} as unknown as TypedDocumentString<CustomerDetailQuery, CustomerDetailQueryVariables>;`,
  "",
].join("\n");

const FILES = definitionFiles([
  ["shipment/table", SHIPMENT_OPERATIONS],
  ["customer/detail", CUSTOMER_OPERATIONS],
]);

describe("definitionFiles", () => {
  it("names each operation's and fragment's document after the file that defines it", () => {
    assert.deepEqual(Object.fromEntries(FILES), {
      shipmentrowfieldsfragmentdoc: "shipment/table",
      shipmenttabledocument: "shipment/table",
      cancelshipmentdocument: "shipment/table",
      customerdetaildocument: "customer/detail",
    });
  });

  it("reads only definitions, not a field that happens to be called query", () => {
    const files = definitionFiles([
      ["inbox/triage", "query TriageItems {\n  items {\n    query\n    position\n  }\n}\n"],
    ]);
    assert.deepEqual(Object.fromEntries(files), { triageitemsdocument: "inbox/triage" });
  });

  it("refuses a name defined in two files", () => {
    assert.throws(
      () =>
        definitionFiles([
          ["a/one", "query Same { a }"],
          ["b/two", "query Same { b }"],
        ]),
      /Same is defined in a\/one and in b\/two/,
    );
  });
});

describe("splitDocuments", () => {
  it("finds the document codegen named in PascalCase for an operation spelt in capitals", () => {
    const files = definitionFiles([
      ["ai/audit", "fragment AIAuditEventFields on AIAuditEvent { id }"],
    ]);
    const source = `${DOCUMENT_CLASS}export const AiAuditEventFieldsFragmentDoc = ${meta({ fragmentName: "AIAuditEventFields" })} as unknown as TypedDocumentString<AiAuditEventFieldsFragment, unknown>;\n`;

    const { modules } = splitDocuments(source, files);
    assert.deepEqual([...modules.keys()], ["ai/audit.ts"]);
  });

  const { graphql, modules } = splitDocuments(GRAPHQL_TS, FILES);

  it("writes one module per operations file holding that file's documents and the types they name", () => {
    assert.deepEqual([...modules.keys()], ["customer/detail.ts", "shipment/table.ts"]);
    assert.equal(
      modules.get("shipment/table.ts"),
      [
        "// Generated by scripts/split-documents.mjs from src/operations/shipment/table.graphql. Do not edit.",
        'import type { TypedDocumentString, CancelShipmentMutation, CancelShipmentMutationVariables, ShipmentRowFieldsFragment, ShipmentTableQuery, ShipmentTableQueryVariables } from "../../graphql";',
        "",
        `export const ShipmentRowFieldsFragmentDoc = ${meta({ fragmentName: "ShipmentRowFields" })} as unknown as TypedDocumentString<ShipmentRowFieldsFragment, unknown>;`,
        `export const ShipmentTableDocument = ${meta({ kind: "query", name: "ShipmentTable", hash: "sha256:aa" })} as unknown as TypedDocumentString<ShipmentTableQuery, ShipmentTableQueryVariables>;`,
        `export const CancelShipmentDocument = ${meta({ kind: "mutation", name: "CancelShipment", hash: "sha256:bb" })} as unknown as TypedDocumentString<CancelShipmentMutation, CancelShipmentMutationVariables>;`,
        "",
      ].join("\n"),
    );
  });

  it("leaves graphql.ts its types and re-exports every document from its module", () => {
    assert.equal(
      graphql,
      [
        "export type ShipmentRowFieldsFragment = { id: string };",
        "export type ShipmentTableQuery = { shipments: unknown };",
        "export type ShipmentTableQueryVariables = { input: unknown };",
        DOCUMENT_CLASS.trimEnd(),
        "",
        'export { CustomerDetailDocument } from "./documents/customer/detail";',
        'export { ShipmentRowFieldsFragmentDoc, ShipmentTableDocument, CancelShipmentDocument } from "./documents/shipment/table";',
        "",
      ].join("\n"),
    );
  });

  it("splits the last document when the file ends without a newline", () => {
    const { graphql: rest, modules: split } = splitDocuments(GRAPHQL_TS.trimEnd(), FILES);
    assert.ok(split.get("customer/detail.ts").includes("export const CustomerDetailDocument"));
    assert.ok(!rest.includes("export const CustomerDetailDocument"));
  });

  it("fails when an operations file defines a document graphql.ts does not have", () => {
    const files = new Map([...FILES, ["orphandocument", "orphan/file"]]);
    assert.throws(
      () => splitDocuments(GRAPHQL_TS, files),
      /no document for a definition in orphan\/file/,
    );
  });

  it("fails when graphql.ts has a document no operations file defines", () => {
    const files = new Map([...FILES].filter(([key]) => key !== "customerdetaildocument"));
    assert.throws(
      () => splitDocuments(GRAPHQL_TS, files),
      /no operations file defines CustomerDetailDocument/,
    );
  });

  it("fails while a document still carries its GraphQL text", () => {
    const unstripped = `${GRAPHQL_TS}export const XFragmentDoc = new TypedDocumentString(\`fragment X on Y { id }\`, {"fragmentName":"X"}) as unknown as TypedDocumentString<XFragment, unknown>;\n`;
    assert.throws(() => splitDocuments(unstripped, FILES), /run strip-fragment-text first/);
  });
});
