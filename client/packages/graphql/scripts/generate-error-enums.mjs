// generate-error-enums.mjs mirrors the Go error taxonomy into TypeScript.
//
// ErrorCode and ProblemType are declared in Go and travel to the client inside
// GraphQL error extensions, which are absent from the SDL — so graphql-codegen has no
// way to see them. Before this generator existed the enums were hand-copied, and a new
// Go value would silently fall through parseProblemType as null with nothing failing.
//
// The retryable set is read from ProblemType.IsInternal() rather than restated, because
// "which faults are the server's own" is a server decision and the client has no
// standing to hold a second opinion.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../../..");

const ERROR_CODE_SOURCE = "services/tms/pkg/errortypes/enums.go";
const PROBLEM_TYPE_SOURCE = "services/tms/internal/api/helpers/problemtypes.go";
const OUTPUT = "client/packages/shared/src/types/generated/error-enums.ts";

// parseConstValues pulls `Ident = Wrapper("value")` pairs out of a Go const block. Both
// enums are declared that way rather than as iota, so the wire value is right there in
// the source and never has to be inferred from declaration order.
function parseConstValues(source, wrapper, sourcePath) {
  const pattern = new RegExp(`(\\w+)\\s*=\\s*${wrapper}\\("([^"]+)"\\)`, "g");
  const entries = [];

  for (const match of source.matchAll(pattern)) {
    entries.push({ identifier: match[1], value: match[2] });
  }

  if (entries.length === 0) {
    throw new Error(
      `No ${wrapper} constants found in ${sourcePath}. The declaration style changed — ` +
        `update the parser in scripts/generate-error-enums.mjs rather than hand-editing ` +
        `the generated output.`,
    );
  }

  return entries;
}

// parseRetryableSet reads the identifiers compared inside ProblemType.IsInternal(). If
// that method is renamed, restructured, or gains a branch this throws instead of
// emitting a silently wrong set — a quietly empty retryable set would disable retry
// everywhere and no test would necessarily catch it.
function parseRetryableSet(source, problemTypes, sourcePath) {
  const method = /func \(t ProblemType\) IsInternal\(\) bool \{\s*return ([^}]+)\}/.exec(source);
  if (!method) {
    throw new Error(
      `Could not locate ProblemType.IsInternal() in ${sourcePath}. It is the source of ` +
        `truth for the retryable set; update the parser if the method moved or was renamed.`,
    );
  }

  const body = method[1];
  const identifiers = [...body.matchAll(/ProblemType(\w+)/g)].map(
    (match) => `ProblemType${match[1]}`,
  );
  const byIdentifier = new Map(problemTypes.map((entry) => [entry.identifier, entry.value]));
  const values = [];

  for (const identifier of identifiers) {
    const value = byIdentifier.get(identifier);
    if (value === undefined) {
      throw new Error(
        `IsInternal() references ${identifier}, which is not a ProblemType constant in ` +
          `${sourcePath}.`,
      );
    }
    if (!values.includes(value)) {
      values.push(value);
    }
  }

  if (values.length === 0) {
    throw new Error(
      `IsInternal() in ${sourcePath} yielded an empty retryable set. Refusing to emit — ` +
        `an empty set silently disables every retry in the client.`,
    );
  }

  return values;
}

function quoteList(values, indent) {
  return values.map((value) => `${indent}"${value}",`).join("\n");
}

function render({ errorCodes, problemTypes, retryable }) {
  return `// Code generated by client/packages/graphql/scripts/generate-error-enums.mjs. DO NOT EDIT.
//
// Source of truth:
//   ${ERROR_CODE_SOURCE} (ErrorCode)
//   ${PROBLEM_TYPE_SOURCE} (ProblemType, ProblemType.IsInternal)
//
// Regenerate with: pnpm --filter @trenova/graphql codegen
// Drift between these values and the Go source fails the codegen:check CI gate.
import { z } from "zod";

export const ErrorCode = z.enum([
${quoteList(errorCodes, "  ")}
]);

export type ErrorCode = z.infer<typeof ErrorCode>;

export const ProblemType = z.enum([
${quoteList(problemTypes, "  ")}
]);

export type ProblemType = z.infer<typeof ProblemType>;

// RETRYABLE_PROBLEM_TYPES is ProblemType.IsInternal() — the faults the server reports as
// its own side of the wire. Anything absent from this set is the caller's to fix and must
// not be replayed.
export const RETRYABLE_PROBLEM_TYPES: readonly ProblemType[] = [
${quoteList(retryable, "  ")}
];

export const retryableProblemTypes: ReadonlySet<ProblemType> = new Set(RETRYABLE_PROBLEM_TYPES);
`;
}

const errorCodeSource = await readFile(resolve(repoRoot, ERROR_CODE_SOURCE), "utf8");
const problemTypeSource = await readFile(resolve(repoRoot, PROBLEM_TYPE_SOURCE), "utf8");

const errorCodeEntries = parseConstValues(errorCodeSource, "ErrorCode", ERROR_CODE_SOURCE);
const problemTypeEntries = parseConstValues(problemTypeSource, "ProblemType", PROBLEM_TYPE_SOURCE);

const contents = render({
  errorCodes: errorCodeEntries.map((entry) => entry.value),
  problemTypes: problemTypeEntries.map((entry) => entry.value),
  retryable: parseRetryableSet(problemTypeSource, problemTypeEntries, PROBLEM_TYPE_SOURCE),
});

const outputPath = resolve(repoRoot, OUTPUT);
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, contents, "utf8");

process.stdout.write(
  `error enums: ${errorCodeEntries.length} ErrorCode, ${problemTypeEntries.length} ProblemType -> ` +
    `${relative(repoRoot, outputPath)}\n`,
);
