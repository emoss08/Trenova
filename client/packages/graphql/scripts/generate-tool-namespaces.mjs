// generate-tool-namespaces.mjs mirrors the server's agent tool namespaces into TypeScript.
//
// An agent tool is named <namespace>_<verb>[_<object>] (docs/engineering/agent-tool-conventions.md),
// and the client reads a tool's verb to say what a step did ("Looked up", "Changed") and to put a
// name back in reading order ("create shipment" for shipment_create). The server owns which
// namespaces exist, in agentports.ToolNamespaces; this generator carries them to the client so the
// two cannot disagree about where a name's verb is.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../../..");

const SOURCE = "services/tms/internal/modules/agent/ports/agentports/toolnamespace.go";
const OUTPUT = "client/packages/shared/src/types/generated/tool-namespaces.ts";

function fail(message) {
  throw new Error(
    `${message} Update the parser in scripts/generate-tool-namespaces.mjs if the Go ` +
      `declaration style changed; never hand-edit the generated output.`,
  );
}

const source = await readFile(resolve(repoRoot, SOURCE), "utf8");
const start = source.search(/^var toolNamespaces = \[\]ToolNamespace\{/m);
if (start < 0) {
  fail(`No var toolNamespaces in ${SOURCE}.`);
}
const names = [...source.slice(start).matchAll(/^\t\tName:\s+"([a-z]+)",$/gm)].map(
  (match) => match[1],
);
if (names.length === 0) {
  fail(`No namespace names in ${SOURCE}.`);
}
const sorted = [...new Set(names)].toSorted();

const body = `// Code generated by client/packages/graphql/scripts/generate-tool-namespaces.mjs. DO NOT EDIT.
//
// Source of truth: ${SOURCE} (agentports.ToolNamespaces).
//
// Regenerate with: pnpm --filter @trenova/graphql codegen
// Drift between these values and the Go source fails the codegen:check CI gate.

/** Every agent tool namespace: a tool is named <namespace>_<verb>[_<object>]. */
export const TOOL_NAMESPACES = [
${sorted.map((name) => `  "${name}",`).join("\n")}
] as const;

export type ToolNamespace = (typeof TOOL_NAMESPACES)[number];
`;

const target = resolve(repoRoot, OUTPUT);
await mkdir(dirname(target), { recursive: true });
await writeFile(target, body);
