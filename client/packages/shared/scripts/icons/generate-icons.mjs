import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const iconSetDir = join(here, "..", "..", "src", "components", "icon-set");
const require = createRequire(import.meta.url);

const BANNED = new Set(["Stars01", "Stars02", "Stars03", "MagicWand01", "MagicWand02"]);
const HAND_WRITTEN = new Set(["AssistMark"]);
const HEADER = "// Generated by packages/shared/scripts/icons/generate-icons.mjs. Do not edit.\n";

function untitledNames() {
  const indexTypes = join(dirname(require.resolve("@untitledui/icons")), "index.d.ts");
  const names = [...readFileSync(indexTypes, "utf8").matchAll(/export \{ (\w+) \} from/g)].map(
    (m) => m[1],
  );
  if (names.length === 0) {
    throw new Error(`no icon exports found in ${indexTypes}`);
  }
  return names.filter((name) => !BANNED.has(name)).sort();
}

function svgBodyToJsx(body) {
  return body
    .replace(/\s+/g, " ")
    .replace(/fill-rule=/g, "fillRule=")
    .replace(/clip-rule=/g, "clipRule=")
    .replace(/<(path|circle|rect|line|polyline|polygon|ellipse)([^>]*?)\s*\/?>/g, "<$1$2 />")
    .trim();
}

function writeUntitled(names) {
  const specifiers = names.map((name) => `  ${name} as ${name}Icon,`).join("\n");
  writeFileSync(
    join(iconSetDir, "untitled.gen.ts"),
    `${HEADER}export {\n${specifiers}\n} from "@untitledui/icons";\n`,
  );
}

function writeCustom(untitled) {
  const custom = JSON.parse(readFileSync(join(here, "custom-icons.json"), "utf8"));
  const taken = new Set(untitled);
  const lines = [];
  for (const name of Object.keys(custom).sort()) {
    if (HAND_WRITTEN.has(name)) {
      continue;
    }
    if (taken.has(name)) {
      throw new Error(`custom icon ${name} collides with the Untitled UI icon of the same name`);
    }
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) {
      throw new Error(`custom icon name ${name} is not PascalCase`);
    }
    const body = svgBodyToJsx(custom[name]);
    lines.push(`export const ${name}Icon = /* @__PURE__ */ createIcon("${name}", <>${body}</>);`);
  }
  writeFileSync(
    join(iconSetDir, "custom.gen.tsx"),
    `${HEADER}import { createIcon } from "./create-icon";\n\n${lines.join("\n")}\n`,
  );
  return lines.length;
}

const names = untitledNames();
writeUntitled(names);
const customCount = writeCustom(names);
console.log(`icons: ${names.length} Untitled UI, ${customCount} custom`);
