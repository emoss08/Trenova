//! The generated constants at the widths the TWAIN calls take.
//!
//! `bindgen` types every `#define` as `u32`, but data argument types, messages,
//! capabilities and most enumerations are `TW_UINT16`. Each narrowing below is
//! checked at compile time, so a value that does not fit fails the build
//! instead of being truncated.

use crate::sys;

macro_rules! narrow_u16 {
    ($($name:ident),* $(,)?) => {
        $(
            #[allow(clippy::cast_possible_truncation)]
            pub const $name: u16 = {
                assert!(sys::$name <= u16::MAX as u32);
                sys::$name as u16
            };
        )*
    };
}

