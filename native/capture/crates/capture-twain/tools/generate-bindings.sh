#!/usr/bin/env bash
# Regenerates src/sys/{x86_64,x86}.rs from the TWAIN Working Group's twain.h.
#
# The header is fetched at a pinned commit of github.com/twain/twain-dsm and
# checked against its SHA-256 before use, so the bindings only change when
# this script's pin does. Needs bindgen-cli (cargo install bindgen-cli) and a
# libclang; nothing here runs at build time.
set -euo pipefail

TWAIN_DSM_COMMIT="a50f7326a191c786ee2d8cb8086aea24309c071f"
TWAIN_H_SHA256="dcae88f5212b8e625724f84dbc738386043dfeb4275db13edf659cd94704db6b"
TWAIN_H_URL="https://raw.githubusercontent.com/twain/twain-dsm/${TWAIN_DSM_COMMIT}/TWAIN_DSM/src/twain.h"

crate_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -sSfL --max-time 60 -o "$work/twain.h" "$TWAIN_H_URL"
echo "${TWAIN_H_SHA256}  $work/twain.h" | sha256sum --check --quiet

# twain.h takes HANDLE, LPVOID and UINT_PTR from windows.h, which is not
# needed for anything else; this supplies exactly those.
write_wrapper() {
  local uint_ptr="$1" win64="$2"
  cat > "$work/wrapper.h" <<WRAP
#define WIN32 1
${win64}
#define PASCAL __stdcall
#define FAR
typedef void *HANDLE;
typedef void *LPVOID;
typedef ${uint_ptr} UINT_PTR;
typedef unsigned char BYTE;
typedef unsigned short wchar_t;
#include "twain.h"
WRAP
}

generate() {
  local target="$1" out="$2"
  bindgen "$work/wrapper.h" \
    --output "$crate_dir/src/sys/$out" \
    --ctypes-prefix 'super::ctypes' \
    --use-core \
    --no-doc-comments \
    --no-prepend-enum-name \
    --default-macro-constant-type unsigned \
    --raw-line '// Generated by tools/generate-bindings.sh from twain.h at' \
    --raw-line "// twain/twain-dsm@${TWAIN_DSM_COMMIT}. Do not edit." \
    --allowlist-type 'TW_(IDENTITY|VERSION|USERINTERFACE|CAPABILITY|ONEVALUE|ENUMERATION|RANGE|ARRAY|STATUS|PENDINGXFERS|EVENT|IMAGEINFO|SETUPMEMXFER|MEMORY|IMAGEMEMXFER|ENTRYPOINT|CALLBACK|EXTIMAGEINFO|INFO|FIX32|FRAME)' \
    --allowlist-type 'DSMENTRYPROC' \
    --allowlist-var '(DG|DF|DAT|MSG|TWRC|TWCC|TWON|TWTY|CAP|ICAP|TWPT|TWSX|TWUN|TWPF|TWCP|TWEI|TWPCH|TWBT|TWBP|TWDE|TWDX|TWPC|TWFY|TWMF|TWLG|TWCY)_[A-Z0-9_]+' \
    -- -x c -I"$work" --target="$target" -fms-extensions
}

write_wrapper "unsigned long long" "#define WIN64 1
#define _WIN64 1
#define _WIN32 1"
generate x86_64-pc-windows-msvc x86_64.rs

write_wrapper "unsigned int" "#define _WIN32 1"
generate i686-pc-windows-msvc x86.rs

rustfmt --edition 2024 "$crate_dir/src/sys/x86_64.rs" "$crate_dir/src/sys/x86.rs"
