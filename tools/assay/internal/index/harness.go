package index

// HarnessFileName is the file injected into the test package through -overlay.
// It never touches the source tree; the overlay makes the compiler see a test
// file that does not exist on disk.
const HarnessFileName = "assay_harness_test.go"

// EnvTestList and EnvCounterDir form the harness contract. With either unset the
// injected TestMain is a plain os.Exit(m.Run()), which is what keeps -test.list
// and the per-test salvage path working against the same binary.
const (
	EnvTestList   = "ASSAY_TEST_LIST"
	EnvCounterDir = "ASSAY_COUNTER_DIR"
)

// initWindowName is the counter window holding init-time execution only: the
// snapshot taken after the sentinel run, before any test has executed.
const initWindowName = "assay-init"

// metaDirName holds the coverage meta blob, written once per package. With
// -coverpkg spanning every module the meta describes the whole workspace, and
// writing a copy into every test's window multiplied that by the test count;
// covdata pairs counters with meta by hash across input directories, which was
// verified empirically before this relied on it.
const metaDirName = "assay-meta"

// harnessLinePrefix starts every progress line the harness prints:
// "assay:harness <name> exit=<code> ns=<int64>".
const harnessLinePrefix = "assay:harness "

const harnessHeader = `// Code generated by assay for coverage indexing. DO NOT EDIT.
//
// assay injects this file into the test package through -overlay while the index
// is built; it is never written to the source tree. It runs every test in one
// process, snapshotting and clearing the coverage counters between tests, so a
// package costs one process instead of one per test. With ` + EnvTestList + `
// or ` + EnvCounterDir + ` unset it behaves exactly like a normal test binary.
`

// HarnessSource renders the injected TestMain for a package.
//
// The protocol is exact and every line of it was verified empirically:
//
//   - a sentinel m.Run with -test.run=^$ comes first, because the coverage
//     machinery finalizes lazily and ClearCounters fails with
//     "covermode=<invalid>" before the first m.Run;
//   - the snapshot taken right after the sentinel holds exactly the package's
//     init-time execution, which the collector merges into every test's ranges
//     for parity with per-process profiles;
//   - test.gocoverdir points at a throwaway directory so the binary's exit-time
//     emission is contained instead of warning on stderr;
//   - the progress line is printed after the snapshot, so a line's presence
//     means the window it names is complete on disk.
func HarnessSource(packageName string) []byte {
	return []byte(harnessHeader + `
package ` + packageName + `

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"runtime/coverage"
	"testing"
	"time"
)

func TestMain(m *testing.M) {
	list := os.Getenv("` + EnvTestList + `")
	counters := os.Getenv("` + EnvCounterDir + `")
	if list == "" || counters == "" {
		os.Exit(m.Run())
	}

	raw, err := os.ReadFile(list)
	if err != nil {
		assayHarnessFail(err)
	}

	_ = flag.Set("test.gocoverdir", filepath.Join(counters, "assay-final"))
	_ = flag.Set("test.run", "^$")
	m.Run()

	meta := filepath.Join(counters, "` + metaDirName + `")
	if err := os.MkdirAll(meta, 0o755); err != nil {
		assayHarnessFail(err)
	}
	if err := coverage.WriteMetaDir(meta); err != nil {
		assayHarnessFail(err)
	}

	assayHarnessSnapshot(counters, "` + initWindowName + `")

	for _, name := range assayHarnessNames(string(raw)) {
		_ = flag.Set("test.run", "^"+name+"$")
		began := time.Now()
		code := m.Run()
		elapsed := time.Since(began)
		assayHarnessSnapshot(counters, name)
		fmt.Printf("` + harnessLinePrefix + `%s exit=%d ns=%d\n", name, code, elapsed.Nanoseconds())
	}

	os.Exit(0)
}

func assayHarnessSnapshot(counters, name string) {
	dir := filepath.Join(counters, name)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		assayHarnessFail(err)
	}
	if err := coverage.WriteCountersDir(dir); err != nil {
		assayHarnessFail(err)
	}
	if err := coverage.ClearCounters(); err != nil {
		assayHarnessFail(err)
	}
}

func assayHarnessFail(err error) {
	fmt.Fprintln(os.Stderr, "assay:harness-error", err)
	os.Exit(3)
}

func assayHarnessNames(raw string) []string {
	var names []string
	start := 0
	for i := 0; i <= len(raw); i++ {
		if i == len(raw) || raw[i] == '\n' {
			if i > start {
				names = append(names, raw[start:i])
			}
			start = i + 1
		}
	}

	return names
}
`)
}
